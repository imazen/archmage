#!/usr/bin/env python3
"""Generate public wrappers from canonical Magemath inventory/source.

No regeneration dependency on deprecated Magetypes implementations. The
migration-only extract-legacy-migration.py is retained solely as provenance.
"""
from pathlib import Path
import json
import re
root=Path(__file__).resolve().parents[2]
out=root/'magemath/src'
rows=json.loads((root/'magemath/docs/legacy-inventory.json').read_text())['methods']
source=(out/'legacy_impl.rs').read_text()
actual=re.findall(r'pub\(crate\) fn (\w+)<T:',source)
assert len(actual)==35 and actual==[r['name']for r in rows],actual
public="""//! Legacy Magetypes transcendental contracts, without inherent-method calls.
//! Backend multiply-add rounding and exceptional-value behavior are preserved.
//! This is distinct from portable/relaxed, whose established special handling
//! remains unchanged. Width16 requires w512; avx512 implies w512.
"""
kernels="pub mod kernels {\n"
for width in [8,4,16]:
    if width!=8:
        if width==16:kernels+='#[cfg(feature="w512")]\n'
        kernels+=f'pub mod f32x{width} {{\n'
    kernels+=f'use magetypes::simd::backends::F32x{width}Convert;\nuse magetypes::simd::generic::f32x{width};\n'
    for row in rows:
        name=row['name'];arg=',n:f32'if row['exponent']else '';call=',n'if row['exponent']else ''
        kernels+=f'/// Legacy `{name}` at width{width}; original backend rounding and specials.\n#[inline(always)]pub fn {name}<T:F32x{width}Convert>(t:T,x:f32x{width}<T>{arg})->f32x{width}<T>{{crate::legacy_impl::width{width}::{name}(t,x{call})}}\n'
    if width!=8:kernels+='}\n'
kernels+='}\n'
public+=kernels
for module in ['array','slice']:
    public+=f'pub mod {module} {{\n'
    for width in [4,8,16]:
        kernel=f'super::kernels::f32x{width}'if width!=8 else 'super::kernels'
        for row in rows:
            name=row['name'];arg=',n:f32'if row['exponent']else '';call=',n'if row['exponent']else ''
            if width==16:public+='#[cfg(feature="w512")]\n'
            public+=f'/// Legacy `{name}` over {"an array"if module=="array"else "a slice"}, using width{width} vector operations.\n'
            public+=f'#[archmage::attune(_*,_*_t,dispatch(inline(hint)),+v4x(cfg(avx512)),define(f32x{width}))]\n'
            if module=='array':
                public+=f'pub fn {name}_f32x{width}(a:[f32;{width}]{arg})->[f32;{width}]{{let t=Token::from_context();{kernel}::{name}(t,f32x{width}::from_array_t(t,a){call}).to_array()}}\n'
            else:
                public+=f'pub fn {name}_f32x{width}(a:&mut[f32]{arg}){{let t=Token::from_context();let(chunks,tail)=a.as_chunks_mut::<{width}>();for chunk in chunks{{*chunk={kernel}::{name}(t,f32x{width}::from_array_t(t,*chunk){call}).to_array();}}if !tail.is_empty(){{let mut pad=[1.0;{width}];pad[..tail.len()].copy_from_slice(tail);let out={kernel}::{name}(t,f32x{width}::from_array_t(t,pad){call}).to_array();tail.copy_from_slice(&out[..tail.len()]);}}}}\n'
    public+='}\n'
(out/'legacy.rs').write_text(public)
# The existing portable/relaxed/unfused arithmetic is separately shared across
# widths, preserving its deliberate special-value differences from legacy.
extra='''//! Additional widths for the existing rounding/special-value families.
//! Generated by tools/generate-legacy.py; wrappers call the shared vector body.
macro_rules! extra_kernels {($step:ident)=>{
'''
for width in [4,16]:
    if width==16:extra+='#[cfg(feature="w512")]\n'
    extra+=f'pub mod f32x{width}{{use magetypes::simd::backends::F32x{width}Convert;use magetypes::simd::generic::f32x{width};\n'
    for row in rows:
        name=row['name'];arg=',n:f32'if row['exponent']else '';call=',n'if row['exponent']else ''
        extra+=f'/// `{name}` using the parent module rounding and special-value contract.\n#[inline(always)]pub fn {name}<T:F32x{width}Convert>(t:T,x:f32x{width}<T>{arg})->f32x{width}<T>{{$crate::bodies::width{width}::{name}::<$crate::bodies::width{width}::$step,T>(t,x{call})}}\n'
    extra+='}\n'
extra+='};}\n'
for module in ['array','slice']:
    extra+=f'macro_rules! extra_{module}s {{()=>{{\n'
    for width in [4,16]:
        for row in rows:
            name=row['name'];arg=',n:f32'if row['exponent']else '';call=',n'if row['exponent']else ''
            if width==16:extra+='#[cfg(feature="w512")]\n'
            extra+=f'/// `{name}` over {"an array"if module=="array"else "a slice"}, following the parent contract.\n'
            extra+=f'#[archmage::attune(_*,_*_t,dispatch(inline(hint)),+v4x(cfg(avx512)),define(f32x{width}))]\n'
            kernel=f'super::kernels::f32x{width}'
            if module=='array':
                extra+=f'pub fn {name}_f32x{width}(a:[f32;{width}]{arg})->[f32;{width}]{{let t=Token::from_context();{kernel}::{name}(t,f32x{width}::from_array_t(t,a){call}).to_array()}}\n'
            else:
                extra+=f'pub fn {name}_f32x{width}(a:&mut[f32]{arg}){{let t=Token::from_context();let(chunks,tail)=a.as_chunks_mut::<{width}>();for chunk in chunks{{*chunk={kernel}::{name}(t,f32x{width}::from_array_t(t,*chunk){call}).to_array();}}if !tail.is_empty(){{let mut pad=[1.0;{width}];pad[..tail.len()].copy_from_slice(tail);let out={kernel}::{name}(t,f32x{width}::from_array_t(t,pad){call}).to_array();tail.copy_from_slice(&out[..tail.len()]);}}}}\n'
    extra+='};}\n'
extra+='pub(crate)use {extra_kernels,extra_arrays,extra_slices};\n'
(out/'width_surfaces.rs').write_text(extra)

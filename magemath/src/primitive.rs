//! Shared diagnostics and one-time primitive backend selection.
#[cfg(any(
    target_arch = "x86_64",
    target_arch = "aarch64",
    target_arch = "wasm32"
))]
use archmage::SimdToken;

/// Why a whole primitive operation was rejected.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub enum PrimitiveErrorKind {
    /// At least one input violates the selected domain.
    InvalidInput,
    /// The requested array width is not supported.
    UnsupportedWidth,
}
/// Whole-vector rejection; no partial output is returned.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct PrimitiveError {
    /// Failure category.
    pub kind: PrimitiveErrorKind,
    /// Rejected lanes, low lane first. Both operands contribute for min/max.
    pub lane_mask: u16,
}
impl core::fmt::Display for PrimitiveError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(
            f,
            "primitive {:?}, lane mask {:#06x}",
            self.kind, self.lane_mask
        )
    }
}
#[cfg(feature = "std")]
impl std::error::Error for PrimitiveError {}

#[derive(Clone, Copy)]
pub(crate) enum Plan {
    #[cfg(target_arch = "x86_64")]
    V3(archmage::X64V3Token),
    #[cfg(all(target_arch = "x86_64", feature = "avx512"))]
    V4(archmage::X64V4Token),
    #[cfg(all(target_arch = "x86_64", feature = "avx512"))]
    V4x(archmage::X64V4xToken),
    #[cfg(target_arch = "aarch64")]
    Neon(archmage::NeonToken),
    #[cfg(target_arch = "wasm32")]
    Wasm(archmage::Wasm128Token),
    Scalar,
}
#[inline(always)]
pub(crate) fn select(caller: bool) -> Plan {
    if caller {
        return Plan::Scalar;
    }
    #[cfg(all(target_arch = "x86_64", feature = "avx512"))]
    {
        if let Some(t) = archmage::X64V4xToken::summon() {
            return Plan::V4x(t);
        }
        if let Some(t) = archmage::X64V4Token::summon() {
            return Plan::V4(t);
        }
    }
    #[cfg(target_arch = "x86_64")]
    if let Some(t) = archmage::X64V3Token::summon() {
        return Plan::V3(t);
    }
    #[cfg(target_arch = "aarch64")]
    if let Some(t) = archmage::NeonToken::summon() {
        return Plan::Neon(t);
    }
    #[cfg(target_arch = "wasm32")]
    if let Some(t) = archmage::Wasm128Token::summon() {
        return Plan::Wasm(t);
    }
    Plan::Scalar
}

// Each invocation supplies a feature kernel generated by #[attune].
macro_rules! dispatch {
    ($plan:expr, $flags:ident, $op:ident, $args:expr, $v3:ident, $v4:ident, $v4x:ident, $neon:ident, $wasm:ident, $scalar:ident) => {
        match $plan {
            #[cfg(target_arch = "x86_64")]
            crate::primitive::Plan::V3(t) => $v3::<$flags, $op>(t, $args),
            #[cfg(all(target_arch = "x86_64", feature = "avx512"))]
            crate::primitive::Plan::V4(t) => $v4::<$flags, $op>(t, $args),
            #[cfg(all(target_arch = "x86_64", feature = "avx512"))]
            crate::primitive::Plan::V4x(t) => $v4x::<$flags, $op>(t, $args),
            #[cfg(target_arch = "aarch64")]
            crate::primitive::Plan::Neon(t) => $neon::<$flags, $op>(t, $args),
            #[cfg(target_arch = "wasm32")]
            crate::primitive::Plan::Wasm(t) => $wasm::<$flags, $op>(t, $args),
            crate::primitive::Plan::Scalar => $scalar::<$flags, $op>(ScalarToken, $args),
        }
    };
}
pub(crate) use dispatch;

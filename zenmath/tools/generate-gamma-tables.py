#!/usr/bin/env python3
"""Regenerate only the approved bit-exact finalist tables (902 binary64 values).

The input was verified by extract-gamma-finalists.py against both archived
compiled Rust and directed MPFR proof records, study commit 1e6cc8e3.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
bits = json.loads((ROOT/'tools/gamma-bits.json').read_text())
assert len(bits) == 902 and all(len(b)==16 for b in bits)
index = 0
def array(shape):
    global index
    if not shape:
        result='f64::from_bits(0x'+bits[index]+')'
        index += 1
        return result
    return '['+','.join(array(shape[1:]) for _ in range(shape[0]))+']'
def rust_type(shape):
    return 'f64' if not shape else '['+rust_type(shape[1:])+';'+str(shape[0])+']'
text='// Selected frozen finalist bits; generated by tools/generate-gamma-tables.py.\n'
for name,shape in [('GLOBAL_DECODE_COEFF',[14]),('GLOBAL_ENCODE_COEFF',[16]),('GLOBAL_FACTOR',[2,10]),('GLOBAL_ERROR',[2,10]),('PIECE_COEFF',[2,16,6]),('PIECE_FACTOR',[2,10,16]),('PIECE_ERROR',[2,10,16])]:
    if name.startswith('GLOBAL_'):
        text+='#[cfg(feature="archmage")]\n'
    text+='pub(crate) const '+name+':'+rust_type(shape)+'='+array(shape)+';\n'
assert index == len(bits)
(ROOT/'src/gamma_tables.rs').write_text(text)

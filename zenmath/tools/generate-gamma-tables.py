#!/usr/bin/env python3
"""Regenerate only the approved bit-exact finalist tables (902 binary64 values).

The input was verified by extract-gamma-finalists.py against both archived
compiled Rust and directed MPFR proof records, study commit 1e6cc8e3.
"""
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
bits = json.loads((ROOT/'tools/gamma-bits.json').read_text())
assert len(bits) == 902 and all(len(b)==16 for b in bits)
index = 0
def array(shape):
    global index
    if not shape:
        result='f64::from_bits(0x'+bits[index]+')'
        index += 1
        return result
    return '['+','.join(array(shape[1:]) for _ in range(shape[0]))+']'
def rust_type(shape):
    return 'f64' if not shape else '['+rust_type(shape[1:])+';'+str(shape[0])+']'
text='// Selected frozen finalist bits; generated by tools/generate-gamma-tables.py.\n'
for name,shape in [('GLOBAL_DECODE_COEFF',[14]),('GLOBAL_ENCODE_COEFF',[16]),('GLOBAL_FACTOR',[2,10]),('GLOBAL_ERROR',[2,10]),('PIECE_COEFF',[2,16,6]),('PIECE_FACTOR',[2,10,16]),('PIECE_ERROR',[2,10,16])]:
    if name.startswith('GLOBAL_'):
        text+='#[cfg(feature="archmage")]\n'
    text+='pub(crate) const '+name+':'+rust_type(shape)+'='+array(shape)+';\n'
assert index == len(bits)
(ROOT/'src/gamma_tables.rs').write_text(text)
# Emit the identical pair/carry/square DAG as named vector expressions. This
# avoids array::map helper boundaries and an addressable vector scratch array.
poly='// Generated by tools/generate-gamma-tables.py; exact certified Estrin DAG.\nuse super::super::packed::{Backend,V};\n'
for name,table,count in [('decode','GLOBAL_DECODE_COEFF',14),('encode','GLOBAL_ENCODE_COEFF',16)]:
    poly+=f'#[inline(always)]\npub(super) fn {name}<T:Backend<N>,const N:usize>(t:T,v:V<T,N>)->V<T,N>{{\n'
    current=[]
    for i in range(count//2):
        item=f'p{i}'
        poly+=f'let {item}=V::splat_t(t,crate::gamma_tables::{table}[{2*i}])+V::splat_t(t,crate::gamma_tables::{table}[{2*i+1}])*v;\n'
        current.append(item)
    power='v';stage=0
    # First pair stage above consumed v. Subsequent stages square that power.
    while len(current)>1:
        stage+=1;next_power=f'v{2**stage}'
        poly+=f'let {next_power}={power}*{power};\n';power=next_power
        new=[]
        for i in range(len(current)//2):
            item=f's{stage}_{i}'
            poly+=f'let {item}={current[2*i]}+{current[2*i+1]}*{power};\n';new.append(item)
        if len(current)%2:new.append(current[-1])
        current=new
    poly+=current[0]+'\n}\n'
poly=re.sub(r'let (s\d+_\d+)=(.*);\n\1\n}',r'\2\n}',poly)
(ROOT/'src/simd/gamma_polynomials.rs').write_text(poly)

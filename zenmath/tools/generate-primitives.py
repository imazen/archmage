"""Generate proof/context scalar primitive entries; numerical algorithms unchanged."""

from pathlib import Path

root = Path(__file__).resolve().parents[1]
s = "//! Scalar instruction kernels and explicit proof entries.\n//! Generated by tools/generate-primitives.py. Default scalar software functions\n//! remain independently callable in crate::scalar; no internal kernel probes.\nuse archmage::prelude::*;\n"
for ty, suffix, prefix, nt, wt in [
    ("f32", "f", "ss", "f32", "f32x4"),
    ("f64", "", "sd", "f64", "f64x2"),
]:
    for op in ["sqrt", "floor", "ceil", "trunc", "roundeven", "round", "fma"]:
        name = op + suffix
        args = "x:" + ty
        if op == "fma":
            args += ", y:" + ty + ", z:" + ty
        call = "x,y,z" if op == "fma" else "x"
        fallback = (
            f"crate::reference::{name}({call})"
            if op != "trunc"
            else f"crate::reference::floor{suffix}(x.abs()).copysign(x)"
        )

        def emit(tier, body, imp=""):
            global s
            s += f"\n/// {op} on {ty}; nearest-even environment, gradual underflow.\n#[archmage::attune(_{tier}, _{tier}_t)]\npub fn {name}({args})->{ty} {{ {imp} {body} }}\n"

        emit("scalar", fallback)
        extract = "_mm_cvtss_f32" if ty == "f32" else "_mm_cvtsd_f64"
        setv = "_mm_set_ss" if ty == "f32" else "_mm_set_sd"
        zero = "_mm_setzero_ps()" if ty == "f32" else "_mm_setzero_pd()"
        imp = "use archmage::intrinsics::x86_64::*;"
        if op == "sqrt":
            body = (
                f"{extract}(_mm_sqrt_{prefix}("
                + (f"{setv}(x)" if ty == "f32" else f"{zero},{setv}(x)")
                + "))"
            )
            tier = "v1"
        elif op == "fma":
            body = f"{extract}(_mm_fmadd_{prefix}({setv}(x),{setv}(y),{setv}(z)))"
            tier = "v3"
        elif op in ["floor", "ceil"]:
            body = f"{extract}(_mm_{op}_{prefix}({zero},{setv}(x)))"
            tier = "v2"
        elif op in ["trunc", "roundeven"]:
            flag = (
                "_MM_FROUND_TO_ZERO" if op == "trunc" else "_MM_FROUND_TO_NEAREST_INT"
            )
            body = f"{extract}(_mm_round_{prefix}::<{{{flag}|_MM_FROUND_NO_EXC}}>({zero},{setv}(x)))"
            tier = "v2"
        else:
            body = f"let t=trunc{suffix}_v2(x); if (x-t).abs()>=0.5 {{ t+1.0_{ty}.copysign(x) }} else {{t}}"
            tier = "v2"
        emit(tier, body, imp if op != "round" else "")
        get = f"vget_lane_{nt}::<0>"
        dup = f"vdup_n_{nt}"
        neon = {
            "sqrt": "vsqrt",
            "floor": "vrndm",
            "ceil": "vrndp",
            "trunc": "vrnd",
            "roundeven": "vrndn",
            "round": "vrnda",
        }
        body = (
            f"{get}({neon[op]}_{nt}({dup}(x)))"
            if op != "fma"
            else f"{get}(vfma_{nt}({dup}(z),{dup}(x),{dup}(y)))"
        )
        emit("neon", body, "use archmage::intrinsics::aarch64::*;")
        wasm = {
            "sqrt": "sqrt",
            "floor": "floor",
            "ceil": "ceil",
            "trunc": "trunc",
            "roundeven": "nearest",
        }
        if op in wasm:
            body = f"{wt}_extract_lane::<0>({wt}_{wasm[op]}({wt}_splat(x)))"
            imp = "use archmage::intrinsics::wasm32::*;"
        elif op == "round":
            body = f"let t=trunc{suffix}_wasm128(x); if (x-t).abs()>=0.5 {{t+1.0_{ty}.copysign(x)}} else {{t}}"
            imp = ""
        else:
            body = fallback
            imp = ""
        emit("wasm128", body, imp)
        s += f"\n/// Select a primitive once; runtime probes require `runtime-dispatch`.\n#[inline]\npub fn {name}({args})->{ty}{{\n"
        choices = (
            [("v3", "X64V3Token", "x86_64")]
            if op == "fma"
            else [
                (
                    "v1" if op == "sqrt" else "v2",
                    "X64V1Token" if op == "sqrt" else "X64V2Token",
                    "x86_64",
                )
            ]
        )
        choices += [
            ("neon", "NeonToken", "aarch64"),
            ("wasm128", "Wasm128Token", "wasm32"),
        ]
        for tier, token, arch in choices:
            s += f'#[cfg(target_arch="{arch}")]\nif let Some(t)=super::available::<{token}>() {{return {name}_{tier}_t(t,{call});}}\n'
        s += f"{name}_scalar_t(ScalarToken,{call})\n}}\n"
primitive_source = s
s = "//! Shared precise scalar contexts; generated by tools/generate-primitives.py.\n"
for name, args in [
    ("expf", "x:f32"),
    ("logf", "x:f32"),
    ("log2f", "x:f32"),
    ("powf", "x:f32,y:f32"),
]:
    call = "x,y" if name == "powf" else "x"
    body = (
        f"crate::gamma::try_gamma({call}).unwrap_or_else(||crate::core_math::powf_with_math(Token::from_context(),{call}))"
        if name == "powf"
        else f"crate::core_math::{name}_in_context({call})"
    )
    gate = 'any(feature="correct-rounding",feature="normal",feature="configurable")' if name=="powf" else 'any(feature="correct-rounding",feature="normal")'
    s += f"\n#[cfg({gate})]\n/// Full scalar CORE-MATH algorithm in a feature context; scalar fallback remains software.\n#[archmage::attune(_v3,_v3_t,_neon,_neon_t,_wasm128,_wasm128_t,_scalar,_scalar_t,_v4x(cfg(avx512)),_v4x_t(cfg(avx512)))]\npub fn {name}({args})->f32{{{body}}}\n"
# Private core-only entries avoid a second candidate guard after ordinary selection.
s += '\n#[cfg(all(feature="runtime-dispatch",any(target_arch="x86_64",target_arch="aarch64"),any(feature="correct-rounding",feature="normal",feature="configurable")))]\n#[archmage::attune(_v3_t,_neon_t)]\npub(crate) fn powf_core(x:f32,y:f32)->f32{crate::core_math::powf_with_math(Token::from_context(),x,y)}\n'
(root / "src/simd/scalar-transcendentals.rs").write_text(s)
primitive_source += '\n#[cfg(feature="correct-rounding")]\npub use super::__scalar_transcendentals::*;\n'
(root / "src/simd/scalar.rs").write_text(primitive_source)

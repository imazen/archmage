#!/usr/bin/env python3
"""Select deterministic MPFR records; no host math supplies expectations."""
from pathlib import Path
import struct
import sys
root=Path(sys.argv[1])
f32='exp2f expf log2f logf log10f cbrtf powf sinf cosf tanf atanf atan2f tanhf log1pf expm1f acosf hypotf'.split()
f64='cbrt exp2 exp log2 log log10 atan log1p sin cos atan2 tan pow atanh tanh asinh'.split()
hard_cases=set('powf atan2f hypotf cbrt exp2 exp log2 log log10 atan log1p sin cos atan2 tan pow atanh tanh asinh'.split())
out=['// Generated by tools/select-core-regressions.py from directed MPFR bounds.', '// Source CORE-MATH 660067dfd3e751c8f07acc31c899ff410aa7206e.', '#![forbid(unsafe_code)]', 'use zenmath::scalar;']
for names,ty,word in [(f32,'f32','I'),(f64,'f64','Q')]:
    for name in names:
        rows=list(struct.iter_unpack('<'+word*3,(root/(name+'.bin')).read_bytes()))
        indices=list(range(144 if name in ['powf','atan2f','atan2','pow','hypotf'] else 12))+list(range(144,160))+list(range(100000,100016))
        chosen=[rows[i] for i in indices]
        wc=root/(name+'-wc.bin')
        if name in hard_cases:chosen+=list(struct.iter_unpack('<'+word*3,wc.read_bytes()))[:32]
        out+=['#[test]',f'fn mpfr_{name}() {{', '#[rustfmt::skip]',f'let cases: [[u{32 if ty=="f32" else 64};3];{len(chosen)}] = [']
        out+=['['+','.join(hex(v) for v in row)+'],' for row in chosen]
        out+= ['];','for [a,b,want] in cases {',f'let a={ty}::from_bits(a);let b={ty}::from_bits(b);',f'let got=scalar::{name}('+('a,b' if name in ['powf','atan2f','atan2','pow','hypotf'] else 'a')+');']
        if name not in ['powf','atan2f','atan2','pow','hypotf']:out+=['let _=b;']
        out+=[f'if {ty}::from_bits(want).is_nan() {{assert!(got.is_nan());}} else {{assert_eq!(got.to_bits(),want,"input={{a:?}}, {{b:?}}");}}','}','}']
Path(__file__).resolve().parents[1].joinpath('tests/core_math.rs').write_text('\n'.join(out)+'\n')

# Exercise the 256-bit fallback directly, independent of fast-path selection.
import math
chosen=[]
for suffix in ['.bin','-wc.bin']:
    count=0
    for a,b,w in struct.iter_unpack('<QQQ',(root/('pow'+suffix)).read_bytes()):
        x,y,want=(struct.unpack('<d',struct.pack('<Q',v))[0] for v in (a,b,w))
        if not (0.25<x<4 and -8<y<8 and y!=int(y) and math.isfinite(want) and want>0):continue
        chosen.append((a,b,w));count+=1
        if count==128:break
assert len(chosen)>=128
text=['// Generated from directed MPFR bounds by select-core-regressions.py.', 'use super::*;', '#[test]', 'fn accurate_power_stage() {', '#[rustfmt::skip]', f'let cases:[[u64;3];{len(chosen)}]=[']
text+=['['+','.join(hex(v) for v in row)+'],' for row in chosen]
text+= ['];','for [a,b,want] in cases {','let x=f64::from_bits(a);let y=f64::from_bits(b);','let r=log3(Q::from_double(x)).mul(Q::from_double(y),4,1);','let got=exp3(r).to_double();','assert_eq!(got.to_bits(),want,"x={x:?}, y={y:?}");','}','}']
Path(__file__).resolve().parents[1].joinpath('src/core_math/pow_tests.rs').write_text('\n'.join(text)+'\n')

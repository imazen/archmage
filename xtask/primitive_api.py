#!/usr/bin/env python3
"""Generate repetitive typed primitive entries; graphs/options remain hand written."""
from pathlib import Path
import argparse, subprocess
ROOT=Path(__file__).resolve().parents[1]

def generate(family):
    binary=family=='minmax'
    options='MinMaxOptions' if binary else 'RecipOptions'
    rows=[('f32',4,'F32x4Backend' if binary else 'F32x4Convert','graph4'),('f32',8,'F32x8Backend' if binary else 'F32x8Convert','graph8'),('f32',16,'F32x16Backend' if binary else 'F32x16Convert','graph16')]
    if binary: rows += [('f64',2,'F64x2Backend','graph64x2'),('f64',4,'F64x4Backend','graph64x4'),('f64',8,'F64x8Backend','graph64x8')]
    out='//! Generated by xtask/primitive_api.py; operation graphs live in mod.rs.\nuse super::*;\nuse archmage::ScalarToken;\nuse crate::primitive::{self,dispatch};\n'
    for f,n,bound,graph in rows:
        v=f'{f}x{n}';kernel=f'kernel_{v}';auto=f'auto_{v}'
        cfg='#[cfg(feature="w512")]\n' if n==(16 if f=='f32' else 8) else ''
        arg=f'([{f};{n}],[{f};{n}])' if binary else f'[{f};{n}]'
        inp=f'{v}::from_array_t(t,args.0),{v}::from_array_t(t,args.1)' if binary else f'{v}::from_array_t(t,args)'
        out+=cfg+f'''#[archmage::magetypes(v4x(cfg(avx512)),v4(cfg(avx512)),v3,neon,wasm128,scalar))]
fn {kernel}<const O:u32,const OP:bool>(t:Token,args:{arg})->Result<[{f};{n}],PrimitiveError>{{
    use magetypes::simd::generic::{v};
    {graph}::<O,OP,_>(t,{inp}).map(|v|v.to_array())
}}
'''.replace('scalar))]','scalar)]')
        out+=cfg+f'''#[inline(always)]
fn {auto}<const O:u32,const OP:bool>(args:{arg})->Result<[{f};{n}],PrimitiveError>{{
    dispatch!(primitive::select(O & {options}::CALLER != 0),O,OP,args,
        {kernel}_v3,{kernel}_v4,{kernel}_v4x,{kernel}_neon,{kernel}_wasm128,{kernel}_scalar)
}}
'''
        for op,bit in ([('min','false'),('max','true')] if binary else [('recip','false'),('rsqrt','true')]):
            name=f'try_{op}_{v}_with';lane=f'try_{op}_{v}_lane_with'
            args=f'a:magetypes::simd::generic::{v}<T>,b:magetypes::simd::generic::{v}<T>' if binary else f'x:magetypes::simd::generic::{v}<T>'
            call='a,b' if binary else 'x'
            out+=cfg+f'''/// Configured {op} retaining the caller's {n}-lane proof; no autonomous upgrade.
#[inline(always)]
pub fn {name}<const O:u32,T:magetypes::simd::backends::{bound}>(t:T,{args})->Result<magetypes::simd::generic::{v}<T>,PrimitiveError>{{
    {graph}::<O,{bit},T>(t,{call})
}}
'''
            lane_args=f'a:{f},b:{f}' if binary else f'x:{f}'
            lane_call=f'V::splat_t(t,a),V::splat_t(t,b)' if binary else 'V::splat_t(t,x)'
            out+=cfg+f'''/// Scalar tail using this exact vector width and proof. Invalid scalar masks contain bit zero only.
#[inline(always)]
pub fn {lane}<const O:u32,T:magetypes::simd::backends::{bound}>(t:T,{lane_args})->Result<{f},PrimitiveError>{{
    use magetypes::simd::generic::{v} as V;
    {name}::<O,T>(t,{lane_call}).map(|v|v.to_array()[0]).map_err(|e|PrimitiveError{{lane_mask:e.lane_mask & 1,..e}})
}}
'''
    for f in (['f32','f64'] if binary else ['f32']):
        widths=[4,8,16] if f=='f32' else [2,4,8];suffix='' if f=='f32' else '_f64'
        for op,bit in ([('min','false'),('max','true')] if binary else [('recip','false'),('rsqrt','true')]):
            name=f'try_{op}{suffix}_array_with';args=f'a:[{f};N],b:[{f};N]' if binary else f'x:[{f};N]'
            out+=f'''/// Configured array {op}, selecting once; widths 1, {widths[0]}, {widths[1]}, and enabled {widths[2]}.
#[inline(always)]
pub fn {name}<const O:u32,const N:usize>({args})->Result<[{f};N],PrimitiveError>{{
    const {{assert!({options}::valid(O),"invalid primitive options");}}
    let mut out=[0.0;N];
'''
            for n in [1]+widths:
                cfg='#[cfg(feature="w512")]\n' if n==widths[-1] else ''
                real=widths[0] if n==1 else n
                ac=f'(core::array::from_fn(|i|a[if N==1{{0}}else{{i}}]),core::array::from_fn(|i|b[if N==1{{0}}else{{i}}]))' if binary else 'core::array::from_fn(|i|x[if N==1{0}else{i}])'
                out+=cfg+f'''if N=={n} {{
    let result=auto_{f}x{real}::<O,{bit}>({ac}).map_err(|e|PrimitiveError{{lane_mask:if N==1{{e.lane_mask & 1}}else{{e.lane_mask}},..e}})?;
    out.copy_from_slice(&result[..N]);return Ok(out);
}}
'''
            out+='Err(PrimitiveError{kind:PrimitiveErrorKind::UnsupportedWidth,lane_mask:0})\n}\n'
            scalar=f'try_{op}{suffix}_with';sa=f'a:{f},b:{f}' if binary else f'x:{f}';sc='[a],[b]' if binary else '[x]'
            lane=f'try_{op}_{f}x{widths[0]}_lane_with'
            if binary:
                body=f'{lane}::<O,_>(ScalarToken,a,b)'
            else:
                body=f'if O & RecipOptions::BACKEND == 0 {{ {lane}::<O,_>(ScalarToken,x) }} else {{ {name}::<O,1>({sc}).map(|v|v[0]) }}'
            note='Scalar min/max needs no CPU detection.' if binary else 'Portable graphs need no CPU detection; native estimates may select once.'
            out+=f'''/// Configured scalar {op}. {note}
#[inline(always)]
pub fn {scalar}<const O:u32>({sa})->Result<{f},PrimitiveError>{{{body}}}
'''
    return out

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for family in ['minmax','recip']:
        text=subprocess.run(['rustfmt','--edition','2024','--emit','stdout'],input=generate(family),text=True,capture_output=True,check=True).stdout
        path=ROOT/'magemath/src'/family/'api.rs'
        if args.check:assert path.read_text()==text,f'{family} API stale'
        else:path.write_text(text)

#!/usr/bin/env python3
"""Generate exact FMA fixtures using rational arithmetic, independently of libm/LLVM.

No floating-point operations are used. Round the exact rational result once to
IEEE binary32/binary64, nearest with ties to even. NaN payloads are not specified.
Run with --check in CI; regeneration is explicit so expectations cannot drift.
"""
from fractions import Fraction
from pathlib import Path
import argparse
import random

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'magetypes/tests/common/fma_vectors.rs'


def power(exponent):
    return Fraction(1 << exponent) if exponent >= 0 else Fraction(1, 1 << -exponent)


def expected(inputs, fraction_bits, exponent_bits):
    bias = (1 << (exponent_bits - 1)) - 1
    sign_bit = 1 << (fraction_bits + exponent_bits)
    exponent_mask = (1 << exponent_bits) - 1
    infinity = exponent_mask << fraction_bits
    nan = infinity | (1 << (fraction_bits - 1))

    def decode(bits):
        sign = bool(bits & sign_bit)
        exponent = (bits >> fraction_bits) & exponent_mask
        mantissa = bits & ((1 << fraction_bits) - 1)
        if exponent == exponent_mask:
            return sign, 'nan' if mantissa else 'inf', None
        value = Fraction(mantissa + ((1 << fraction_bits) if exponent else 0))
        value *= power((exponent or 1) - bias - fraction_bits)
        return sign, 'finite', -value if sign else value

    a, b, c = map(decode, inputs)
    if any(x[1] == 'nan' for x in (a, b, c)):
        return nan
    product_sign = a[0] ^ b[0]
    if a[1] == 'inf' or b[1] == 'inf':
        if a[2] == 0 or b[2] == 0 or (c[1] == 'inf' and c[0] != product_sign):
            return nan
        return infinity | (sign_bit if product_sign else 0)
    if c[1] == 'inf':
        return inputs[2]
    value = a[2] * b[2] + c[2]
    if value == 0:
        negative_zero = (a[2] == 0 or b[2] == 0) and c[2] == 0 and product_sign and c[0]
        return sign_bit if negative_zero else 0
    sign = sign_bit if value < 0 else 0
    value = abs(value)
    exponent = value.numerator.bit_length() - value.denominator.bit_length()
    if value < power(exponent):
        exponent -= 1
    quantum = max(exponent, 1 - bias) - fraction_bits
    scaled = value / power(quantum)
    significand, remainder = divmod(scaled.numerator, scaled.denominator)
    if 2 * remainder > scaled.denominator or (2 * remainder == scaled.denominator and significand & 1):
        significand += 1
    if significand >= 1 << (fraction_bits + 1):
        significand >>= 1
        quantum += 1
    exponent = quantum + fraction_bits
    if exponent > bias:
        return sign | infinity
    if significand < 1 << fraction_bits:
        return sign | significand
    return sign | ((exponent + bias) << fraction_bits) | (significand - (1 << fraction_bits))


def cases(fraction_bits, exponent_bits):
    width = fraction_bits + exponent_bits + 1
    sign = 1 << (width - 1)
    bias = (1 << (exponent_bits - 1)) - 1
    one = bias << fraction_bits
    half = one - (1 << fraction_bits)
    two = one + (1 << fraction_bits)
    infinity = ((1 << exponent_bits) - 1) << fraction_bits
    maximum = infinity - 1
    minimum = 1 << fraction_bits
    values = [
        (maximum, two, maximum | sign), (maximum, two, 0),
        (minimum | 1, half, sign | 1), (1, half, 0), (1, half, sign),
        (3, half, 0), (1, 1, 0), (1, sign | 1, 0),
        (one, one, one | sign), (one | 1, one | 1, (one | 2) | sign),
        (0, infinity, one), (infinity, one, infinity | sign),
        (infinity, sign | one, one), (one, one, infinity),
        (infinity | 1, one, 0), (one, infinity | 1, 0),
    ]
    for a in (0, sign):
        for b in (one, one | sign):
            for c in (0, sign):
                values.append((a, b, c))
    for exponent in (1, 2, 3, bias - 1, bias, bias + 1, 2 * bias - 1):
        a = (exponent << fraction_bits) | 1
        values.extend([(a, one - 1, a | sign), (a, one + 1, a | sign)])
    if width == 32:
        values.extend([(0x97000800, 0x1cfff001, 0x00010002),
                       (0x33800001, 0x3f7ffffe, 0x3f800001)])
    # Negate exact results without changing their magnitude; cover signed underflow.
    values += [(a ^ sign, b, c ^ sign) for a, b, c in list(values)]
    rng = random.Random(0xF0A000 + width)
    while len(values) < 128:
        values.append(tuple(rng.getrandbits(width) for _ in range(3)))
    return values


def render():
    assert expected((0x97000800, 0x1cfff001, 0x00010002), 23, 8) == 0x00010001
    assert expected((0x3ff0000002000000, 0x3ff0000002000000, 0xbff0000004000000), 52, 11) == 969 << 52
    out = ['// Generated by xtask/fma_vectors.py using exact rational arithmetic.',
           '// Each row is [a bits, b bits, c bits, correctly rounded (a*b+c) bits].',
           '// NaN expectations assert NaN-ness, not a particular payload or sign.']
    for width, fraction_bits, exponent_bits in [(32, 23, 8), (64, 52, 11)]:
        rows = cases(fraction_bits, exponent_bits)
        out += ['#[rustfmt::skip]', f'pub const F{width}: [[u{width}; 4]; {len(rows)}] = [']
        for row in rows:
            bits = (*row, expected(row, fraction_bits, exponent_bits))
            out.append('    [' + ', '.join(f'0x{x:0{width // 4}x}' for x in bits) + '],')
        out.append('];')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    contents = render()
    if args.check:
        if OUTPUT.read_text() != contents:
            raise SystemExit('FMA fixtures differ; review before regenerating expectations')
    else:
        OUTPUT.write_text(contents)

#!/usr/bin/env python3
"""Independent exact-rational reciprocal and rsqrt rounding fixtures (f32).

Mathematical rsqrt compares x*y*y with 1 at rounding midpoints. The separate
sqrt-then-divide reference is intentionally recorded as a different column.
"""
from fractions import Fraction
from pathlib import Path
import argparse
from sqrt_vectors import value, oracle as sqrt_oracle
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'magemath/tests/data/reciprocal_vectors.rs'
P,E=23,8
SIGN=1<<31
INF=0x7f800000
NAN=0x7fc00000

def round_positive(x):
    low,high=0,INF
    while low+1<high:
        middle=(low+high)//2
        if value(middle,P,E)<=x:low=middle
        else:high=middle
    midpoint=(value(low,P,E)+value(high,P,E))/2
    return low if x<midpoint or (x==midpoint and not low&1) else high

def reciprocal(bits):
    sign=bits&SIGN; mag=bits&~SIGN
    if mag>INF:return NAN
    if mag==0:return sign|INF
    if mag==INF:return sign
    return sign|round_positive(1/value(mag,P,E))

def rsqrt(bits):
    mag=bits&~SIGN
    if mag==0:return (bits&SIGN)|INF
    if bits&SIGN or mag>INF:return NAN
    if mag==INF:return 0
    x=value(bits,P,E)
    low,high=0,INF
    while low+1<high:
        middle=(low+high)//2
        if value(middle,P,E)**2*x<=1:low=middle
        else:high=middle
    midpoint=(value(low,P,E)+value(high,P,E))/2
    test=midpoint**2*x
    return low if test>1 or (test==1 and not low&1) else high

def generate():
    inputs={0,SIGN,INF,INF|SIGN,INF|1,NAN,NAN|SIGN}
    for e in [0,1,2,3,62,63,64,125,126,127,128,129,190,191,192,251,252,253,254]:
        for m in [0,1,0x3fffff,0x400000,0x7ffffe,0x7fffff]:
            inputs.add((e<<P)|m)
    state=0x12345678
    for _ in range(64):
        state=(1664525*state+1013904223)&0xffffffff;inputs.add(state)
    text='// Generated by xtask/reciprocal_vectors.py; exact rational midpoint oracle.\n'
    text+='// (input, rounded reciprocal, rounded mathematical rsqrt, sqrt-then-divide)\n'
    text+='pub const F32: &[(u32, u32, u32, u32)] = &[\n'
    for x in sorted(inputs):text+=f'    (0x{x:08x}, 0x{reciprocal(x):08x}, 0x{rsqrt(x):08x}, 0x{reciprocal(sqrt_oracle(x,P,E)):08x}),\n'
    return text+'];\n'
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();text=generate()
    assert len(text.encode())<30000
    if args.check:assert OUT.read_text()==text,'reciprocal fixtures stale'
    else:OUT.parent.mkdir(parents=True,exist_ok=True);OUT.write_text(text)

#!/usr/bin/env python3
"""Exact rational sqrt fixtures: compare x with squared rounding midpoints.

No libm sqrt or production algorithm participates in this oracle.
"""
from fractions import Fraction
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'magetypes/tests/data/sqrt_vectors.rs'


def value(bits, precision, exponent_bits):
    bias = (1 << (exponent_bits - 1)) - 1
    exponent, mantissa = bits >> precision, bits & ((1 << precision) - 1)
    if exponent:
        mantissa |= 1 << precision
    power = (exponent or 1) - bias - precision
    return Fraction(mantissa << max(0, power), 1 << max(0, -power))


def oracle(bits, precision, exponent_bits):
    sign = 1 << (precision + exponent_bits)
    infinity = ((1 << exponent_bits) - 1) << precision
    nan = infinity | (1 << (precision - 1))
    if bits & ~sign == 0:
        return bits
    if bits >= infinity:
        return infinity if bits == infinity else nan
    x = value(bits, precision, exponent_bits)
    low, high = 0, infinity - 1
    while low + 1 < high:
        middle = (low + high) // 2
        if value(middle, precision, exponent_bits) ** 2 <= x:
            low = middle
        else:
            high = middle
    midpoint = (value(low, precision, exponent_bits) + value(high, precision, exponent_bits)) / 2
    square = midpoint ** 2
    return low if x < square or (x == square and low & 1 == 0) else high


def cases(precision, exponent_bits):
    sign = 1 << (precision + exponent_bits)
    infinity = ((1 << exponent_bits) - 1) << precision
    bias = (1 << (exponent_bits - 1)) - 1
    exponents = [0, 1, 2, bias // 2, bias // 2 + 1, bias - 2,
                 bias - 1, bias, bias + 1, bias + 2, bias * 3 // 2,
                 2 * bias - 1, 2 * bias]
    mantissas = [0, 1, 2, (1 << (precision - 1)) - 1,
                 1 << (precision - 1), (1 << (precision - 1)) + 1,
                 (1 << precision) - 2, (1 << precision) - 1]
    inputs = {0, sign, infinity, infinity | sign, infinity | 1,
              infinity | (1 << (precision - 1)), infinity | sign | 1}
    inputs.update((exponent << precision) | m for exponent in exponents for m in mantissas)
    state = 0x9e3779b97f4a7c15
    for _ in range(128):
        state ^= state << 13
        state ^= state >> 7
        state ^= state << 17
        state &= (1 << 64) - 1
        inputs.add(state & ((sign << 1) - 1))
    return sorted(inputs)


def generate():
    text = '// Generated by xtask/sqrt_vectors.py; exact rational squared-midpoint oracle.\n'
    for name, precision, exponent_bits, width in [('F32', 23, 8, 8), ('F64', 52, 11, 16)]:
        text += f'pub const {name}: &[(u{width * 4}, u{width * 4})] = &[\n'
        for bits in cases(precision, exponent_bits):
            expected = oracle(bits, precision, exponent_bits)
            text += f'    (0x{bits:0{width}x}, 0x{expected:0{width}x}),\n'
        text += '];\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        assert OUTPUT.read_text() == text, 'sqrt fixtures are stale'
    else:
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_text(text)

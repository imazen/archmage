//! Generator for repetitive typed `magemath` primitive entrypoints (`minmax`, `recip`).
//!
//! Operation graphs and option bitfields remain hand-written in each module's
//! `mod.rs`; this module emits `magemath/src/{minmax,recip}/api.rs` using
//! `#[archmage::attune]` and formats through `rustfmt --edition 2024`.

use anyhow::{Context, Result, bail};
use std::fmt::Write as _;
use std::fs;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Stdio};

#[derive(Clone, Copy)]
enum Family {
    MinMax,
    Recip,
}

impl Family {
    fn dir_name(self) -> &'static str {
        match self {
            Self::MinMax => "minmax",
            Self::Recip => "recip",
        }
    }

    fn options_type(self) -> &'static str {
        match self {
            Self::MinMax => "MinMaxOptions",
            Self::Recip => "RecipOptions",
        }
    }

    fn is_binary(self) -> bool {
        matches!(self, Self::MinMax)
    }

    fn ops(self) -> &'static [(&'static str, &'static str)] {
        match self {
            Self::MinMax => &[("min", "false"), ("max", "true")],
            Self::Recip => &[("recip", "false"), ("rsqrt", "true")],
        }
    }
}

fn render_family(family: Family) -> String {
    let binary = family.is_binary();
    let options = family.options_type();
    let mut rows: Vec<(&str, usize, &str, &str)> = vec![
        (
            "f32",
            4,
            if binary {
                "F32x4Backend"
            } else {
                "F32x4Convert"
            },
            "graph4",
        ),
        (
            "f32",
            8,
            if binary {
                "F32x8Backend"
            } else {
                "F32x8Convert"
            },
            "graph8",
        ),
        (
            "f32",
            16,
            if binary {
                "F32x16Backend"
            } else {
                "F32x16Convert"
            },
            "graph16",
        ),
    ];
    if binary {
        rows.extend([
            ("f64", 2, "F64x2Backend", "graph64x2"),
            ("f64", 4, "F64x4Backend", "graph64x4"),
            ("f64", 8, "F64x8Backend", "graph64x8"),
        ]);
    }

    let mut out = String::from(
        "//! Generated by `cargo xtask generate`; operation graphs live in `mod.rs`.\n\
         use super::*;\n\
         use archmage::ScalarToken;\n\
         use crate::primitive::{self, dispatch};\n\n",
    );

    for (elem, lanes, bound, graph) in rows {
        let vec_ty = format!("{elem}x{lanes}");
        let kernel = format!("kernel_{vec_ty}");
        let auto = format!("auto_{vec_ty}");
        let w512_lanes = if elem == "f32" { 16 } else { 8 };
        let cfg = if lanes == w512_lanes {
            "#[cfg(feature = \"w512\")]\n"
        } else {
            ""
        };
        let arg_ty = if binary {
            format!("([{elem}; {lanes}], [{elem}; {lanes}])")
        } else {
            format!("[{elem}; {lanes}]")
        };
        let inputs = if binary {
            format!("{vec_ty}::from_array_t(t, args.0), {vec_ty}::from_array_t(t, args.1)")
        } else {
            format!("{vec_ty}::from_array_t(t, args)")
        };

        let _ = writeln!(
            out,
            "{cfg}#[archmage::attune(_v4x_t(cfg(avx512)), _v4_t(cfg(avx512)), _v3_t, _neon_t, _wasm128_t, _scalar_t)]\n\
             fn {kernel}<const O: u32, const OP: bool>(t: Token, args: {arg_ty}) -> Result<[{elem}; {lanes}], PrimitiveError> {{\n\
                 use magetypes::simd::generic::{vec_ty};\n\
                 {graph}::<O, OP, _>(t, {inputs}).map(|v| v.to_array())\n\
             }}\n"
        );

        let _ = writeln!(
            out,
            "{cfg}#[inline(always)]\n\
             fn {auto}<const O: u32, const OP: bool>(args: {arg_ty}) -> Result<[{elem}; {lanes}], PrimitiveError> {{\n\
                 dispatch!(\n\
                     primitive::select(O & {options}::CALLER != 0),\n\
                     O,\n\
                     OP,\n\
                     args,\n\
                     {kernel}_v3_t,\n\
                     {kernel}_v4_t,\n\
                     {kernel}_v4x_t,\n\
                     {kernel}_neon_t,\n\
                     {kernel}_wasm128_t,\n\
                     {kernel}_scalar_t\n\
                 )\n\
             }}\n"
        );

        for &(op, bit) in family.ops() {
            let name = format!("try_{op}_{vec_ty}_with");
            let lane = format!("try_{op}_{vec_ty}_lane_with");
            let fn_args = if binary {
                format!(
                    "a: magetypes::simd::generic::{vec_ty}<T>, b: magetypes::simd::generic::{vec_ty}<T>"
                )
            } else {
                format!("x: magetypes::simd::generic::{vec_ty}<T>")
            };
            let call_args = if binary { "a, b" } else { "x" };
            let _ = writeln!(
                out,
                "{cfg}/// Configured {op} retaining the caller's {lanes}-lane proof; no autonomous upgrade.\n\
                 #[inline(always)]\n\
                 pub fn {name}<const O: u32, T: magetypes::simd::backends::{bound}>(\n\
                     t: T,\n\
                     {fn_args},\n\
                 ) -> Result<magetypes::simd::generic::{vec_ty}<T>, PrimitiveError> {{\n\
                     {graph}::<O, {bit}, T>(t, {call_args})\n\
                 }}\n"
            );

            let lane_args = if binary {
                format!("a: {elem}, b: {elem}")
            } else {
                format!("x: {elem}")
            };
            let lane_call = if binary {
                "V::splat_t(t, a), V::splat_t(t, b)"
            } else {
                "V::splat_t(t, x)"
            };
            let _ = writeln!(
                out,
                "{cfg}/// Scalar tail using this exact vector width and proof. Invalid scalar masks contain bit zero only.\n\
                 #[inline(always)]\n\
                 pub fn {lane}<const O: u32, T: magetypes::simd::backends::{bound}>(\n\
                     t: T,\n\
                     {lane_args},\n\
                 ) -> Result<{elem}, PrimitiveError> {{\n\
                     use magetypes::simd::generic::{vec_ty} as V;\n\
                     {name}::<O, T>(t, {lane_call})\n\
                         .map(|v| v.to_array()[0])\n\
                         .map_err(|e| PrimitiveError {{ lane_mask: e.lane_mask & 1, ..e }})\n\
                 }}\n"
            );
        }
    }

    let elems: &[&str] = if binary { &["f32", "f64"] } else { &["f32"] };
    for &elem in elems {
        let widths: [usize; 3] = if elem == "f32" { [4, 8, 16] } else { [2, 4, 8] };
        let suffix = if elem == "f32" { "" } else { "_f64" };
        for &(op, bit) in family.ops() {
            let arr_name = format!("try_{op}{suffix}_array_with");
            let arr_args = if binary {
                format!("a: [{elem}; N], b: [{elem}; N]")
            } else {
                format!("x: [{elem}; N]")
            };
            let _ = writeln!(
                out,
                "/// Configured array {op}, selecting once; widths 1, {}, {}, and enabled {}.\n\
                 #[inline(always)]\n\
                 pub fn {arr_name}<const O: u32, const N: usize>({arr_args}) -> Result<[{elem}; N], PrimitiveError> {{\n\
                     const {{ assert!({options}::valid(O), \"invalid primitive options\"); }}\n\
                     let mut out = [0.0; N];",
                widths[0], widths[1], widths[2]
            );
            for n in [1, widths[0], widths[1], widths[2]] {
                let cfg = if n == widths[2] {
                    "#[cfg(feature = \"w512\")]\n"
                } else {
                    ""
                };
                let real = if n == 1 { widths[0] } else { n };
                let pack_expr = if binary {
                    "(core::array::from_fn(|i| a[if N == 1 { 0 } else { i }]), core::array::from_fn(|i| b[if N == 1 { 0 } else { i }]))"
                } else {
                    "core::array::from_fn(|i| x[if N == 1 { 0 } else { i }])"
                };
                let _ = writeln!(
                    out,
                    "{cfg}if N == {n} {{\n\
                         let result = auto_{elem}x{real}::<O, {bit}>({pack_expr})\n\
                             .map_err(|e| PrimitiveError {{ lane_mask: if N == 1 {{ e.lane_mask & 1 }} else {{ e.lane_mask }}, ..e }})?;\n\
                         out.copy_from_slice(&result[..N]);\n\
                         return Ok(out);\n\
                     }}"
                );
            }
            out.push_str(
                "Err(PrimitiveError { kind: PrimitiveErrorKind::UnsupportedWidth, lane_mask: 0 })\n}\n\n",
            );

            let scalar_fn = format!("try_{op}{suffix}_with");
            let scalar_args = if binary {
                format!("a: {elem}, b: {elem}")
            } else {
                format!("x: {elem}")
            };
            let scalar_pack = if binary { "[a], [b]" } else { "[x]" };
            let lane_fn = format!("try_{op}_{elem}x{}_lane_with", widths[0]);
            let body = if binary {
                format!("{lane_fn}::<O, _>(ScalarToken, a, b)")
            } else {
                format!(
                    "if O & 6 == 0 {{ {lane_fn}::<O, _>(ScalarToken, x) }} else {{ {arr_name}::<O, 1>({scalar_pack}).map(|v| v[0]) }}"
                )
            };
            let note = if binary {
                "Scalar min/max needs no CPU detection."
            } else {
                "Approximate graphs select one provider for the whole operation; HIGHP needs no CPU detection."
            };
            let _ = writeln!(
                out,
                "/// Configured scalar {op}. {note}\n\
                 #[inline(always)]\n\
                 pub fn {scalar_fn}<const O: u32>({scalar_args}) -> Result<{elem}, PrimitiveError> {{\n\
                     {body}\n\
                 }}\n"
            );
        }
    }

    out
}

fn rustfmt_str(code: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("spawning rustfmt")?;
    child
        .stdin
        .take()
        .context("rustfmt stdin")?
        .write_all(code.as_bytes())?;
    let out = child.wait_with_output().context("waiting on rustfmt")?;
    if !out.status.success() {
        bail!(
            "rustfmt failed on generated magemath primitive API:\n{}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    String::from_utf8(out.stdout).context("rustfmt stdout not UTF-8")
}

/// Generate or verify `magemath/src/{minmax,recip}/api.rs`.
pub fn generate_magemath_primitives(root: &Path, check_only: bool) -> Result<()> {
    for family in [Family::MinMax, Family::Recip] {
        let formatted = rustfmt_str(&render_family(family))?;
        let path = root
            .join("magemath/src")
            .join(family.dir_name())
            .join("api.rs");
        if check_only {
            let existing =
                fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
            if existing != formatted {
                bail!(
                    "{} is stale; run `cargo run -p xtask -- generate`",
                    path.display()
                );
            }
        } else {
            fs::write(&path, &formatted).with_context(|| format!("writing {}", path.display()))?;
            println!("  Wrote {} ({} bytes)", path.display(), formatted.len());
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_attune_and_no_legacy_macros() {
        for family in [Family::MinMax, Family::Recip] {
            let src = render_family(family);
            assert!(src.contains("#[archmage::attune("));
            assert!(!src.contains("archmage::magetypes"));
            assert!(!src.contains("archmage::arcane"));
            assert!(!src.contains("archmage::rite"));
            let formatted = rustfmt_str(&src).expect("generated source must format cleanly");
            assert_eq!(
                formatted,
                rustfmt_str(&formatted).unwrap(),
                "rustfmt must be idempotent"
            );
        }
    }
}

/// Generate `impls/x86_v3_higher_delegated.rs` for `X64V3CryptoToken`,
/// `X64V3GfniCryptoToken`, and `X64V3VnniToken`.
pub(crate) fn generate_x86_v3_higher(
    narrow_specs: &[(String, String)],
    w512_specs: &[(String, String)],
) -> String {
    let impls = emit_all_trait_impls(
        narrow_specs,
        w512_specs,
        quote! { $token },
        "archmage::X64V3Token",
        "self.v3()",
        &[],
    );

    formatdoc! {r#"
        //! Full SIMD backend delegation for `X64V3CryptoToken`,
        //! `X64V3GfniCryptoToken`, and `X64V3VnniToken` → `X64V3Token`.
        //! Generated by xtask from the backend trait definitions; do not edit.
        //!
        //! ## Deductive safety proof
        //!
        //! `X64V3Token`'s feature set is a strict subset of `X64V3CryptoToken`,
        //! `X64V3GfniCryptoToken`, and `X64V3VnniToken`, so every instruction
        //! executed by `X64V3Token`'s backend implementations is proven safe
        //! via `self.v3()`. `Self::Repr` aliases `X64V3Token`'s representation
        //! identically across W128, W256, and W512 polyfills.

        #![cfg(target_arch = "x86_64")]

        use crate::simd::backends::*;

        macro_rules! delegate_v3_tier {{
            ($token:ty) => {{
                {impls}
            }};
        }}

        delegate_v3_tier!(archmage::X64V3CryptoToken);
        delegate_v3_tier!(archmage::X64V3GfniCryptoToken);
        delegate_v3_tier!(archmage::X64V3VnniToken);
    "#}
}

/// Generate `impls/arm_higher_delegated.rs` for `Arm64V2Token` and `Arm64V3Token`.
pub(crate) fn generate_arm_higher(
    narrow_specs: &[(String, String)],
    w512_specs: &[(String, String)],
) -> String {
    let impls = emit_all_trait_impls(
        narrow_specs,
        w512_specs,
        quote! { $token },
        "archmage::NeonToken",
        "self.neon()",
        &[],
    );

    formatdoc! {r#"
        //! Full SIMD backend delegation for `Arm64V2Token` and `Arm64V3Token`
        //! → `NeonToken`. Generated by xtask from the backend trait
        //! definitions; do not edit.
        //!
        //! ## Deductive safety proof
        //!
        //! `NeonToken`'s feature set (`neon`) is a strict subset of both
        //! `Arm64V2Token` (`neon,crc,rdm,dotprod,fp16,aes,sha2`) and
        //! `Arm64V3Token` (`Arm64V2 + fhm,fcma,sha3,i8mm,bf16`), so forwarding
        //! baseline SIMD operations through `self.neon()` is sound while
        //! allowing `#[arcane]` / `#[rite]` / `#[magetypes]` kernels to hold
        //! the higher-tier token and emit `rdm`, `dotprod`, `fp16`, `fhm`, and
        //! `i8mm` instructions in the same codegen region.

        #![cfg(target_arch = "aarch64")]

        use crate::simd::backends::*;

        macro_rules! delegate_neon_tier {{
            ($token:ty) => {{
                {impls}
            }};
        }}

        delegate_neon_tier!(archmage::Arm64V2Token);
        delegate_neon_tier!(archmage::Arm64V3Token);
    "#}
}

/// Generate `impls/wasm128_relaxed_delegated.rs` for `Wasm128RelaxedToken`.
pub(crate) fn generate_wasm_relaxed(
    narrow_specs: &[(String, String)],
    w512_specs: &[(String, String)],
) -> String {
    let impls = emit_all_trait_impls(
        narrow_specs,
        w512_specs,
        quote! { archmage::Wasm128RelaxedToken },
        "archmage::Wasm128Token",
        "self.wasm128()",
        WASM_RELAXED_OVERRIDES,
    );

    formatdoc! {r#"
        //! Full SIMD backend delegation for `Wasm128RelaxedToken` →
        //! `Wasm128Token`, with per-function `relaxed-simd` overrides for
        //! `mul_add`, `mul_sub`, `mul_add_portable`, and `mul_sub_portable`.
        //! Generated by xtask from the backend trait definitions; do not edit.
        //!
        //! ## Deductive safety proof
        //!
        //! `Wasm128Token` (`simd128`) is a strict subset of
        //! `Wasm128RelaxedToken` (`simd128,relaxed-simd`), so baseline SIMD
        //! operations forward soundly via `self.wasm128()`. Multiply-add
        //! methods dispatch to `crate::wasm_fma::*_relaxed`, which carry
        //! `#[archmage::rite]` (`#[target_feature(enable = "simd128,relaxed-simd")]`)
        //! so `f32x4.relaxed_madd` / `f64x2.relaxed_madd` are emitted per
        //! function even when the crate is compiled without global
        //! `-C target-feature=+relaxed-simd`.

        #![cfg(target_arch = "wasm32")]

        use crate::simd::backends::*;

        {impls}
    "#}
}

fn emit_all_trait_impls(
    narrow_specs: &[(String, String)],
    w512_specs: &[(String, String)],
    target_tokens: impl quote::ToTokens,
    base_token: &str,
    extract_expr: &str,
    overrides: &[(&str, &str, &str)],
) -> String {
    let mut out = String::new();
    for (trait_name, src) in narrow_specs {
        let trait_item = find_trait(src, trait_name);
        out.push_str(&delegating_impl(
            trait_name,
            &trait_item,
            &target_tokens,
            base_token,
            extract_expr,
            false,
            overrides,
        ));
    }
    for (trait_name, src) in w512_specs {
        let trait_item = find_trait(src, trait_name);
        out.push_str(&delegating_impl(
            trait_name,
            &trait_item,
            &target_tokens,
            base_token,
            extract_expr,
            true,
            overrides,
        ));
    }
    out
}

fn find_trait(src: &str, name: &str) -> syn::ItemTrait {
    let file = syn::parse_file(src).expect("generated backend trait source must parse");
    file.items
        .into_iter()
        .find_map(|item| match item {
            Item::Trait(t) if t.ident == name => Some(t),
            _ => None,
        })
        .unwrap_or_else(|| panic!("trait {name} not found in generated source"))
}

fn delegating_impl(
    trait_name: &str,
    trait_item: &syn::ItemTrait,
    target_tokens: &impl quote::ToTokens,
    base_token: &str,
    extract_expr: &str,
    w512_gated: bool,
    overrides: &[(&str, &str, &str)],
) -> String {
    let trait_ident = format_ident!("{trait_name}");
    let base_path: syn::Path = syn::parse_str(base_token).expect("base token path");
    let extract: syn::Expr = syn::parse_str(extract_expr).expect("extract expression");
    let mut methods = Vec::new();
    for item in &trait_item.items {
        let TraitItem::Fn(method) = item else {
            continue;
        };
        let sig: syn::Signature = syn::parse_str(
            &method
                .sig
                .to_token_stream()
                .to_string()
                .replace("super ::", "crate :: simd :: backends ::"),
        )
        .expect("method signature re-parse");
        let name = &sig.ident;
        assert!(
            matches!(sig.inputs.first(), Some(FnArg::Receiver(_))),
            "{trait_name}::{name} has no receiver; delegation requires `self`"
        );
        let args: Vec<syn::Ident> = sig
            .inputs
            .iter()
            .skip(1)
            .map(|arg| match arg {
                FnArg::Typed(pat) => match pat.pat.as_ref() {
                    Pat::Ident(p) => p.ident.clone(),
                    other => panic!(
                        "{trait_name}::{name}: parameter pattern `{}` is not an identifier",
                        other.to_token_stream()
                    ),
                },
                FnArg::Receiver(_) => unreachable!("receiver after the first parameter"),
            })
            .collect();
        let turbofish = {
            let params: Vec<_> = sig
                .generics
                .params
                .iter()
                .map(|p| match p {
                    syn::GenericParam::Type(t) => t.ident.to_token_stream(),
                    syn::GenericParam::Const(c) => c.ident.to_token_stream(),
                    syn::GenericParam::Lifetime(l) => l.lifetime.to_token_stream(),
                })
                .collect();
            if params.is_empty() {
                quote! {}
            } else {
                quote! { ::<#(#params),*> }
            }
        };
        let override_helper = overrides
            .iter()
            .find(|(t, m, _)| *t == trait_name && name == m)
            .map(|(_, _, helper)| format_ident!("{helper}"));
        let body = match override_helper {
            Some(helper) => quote! { crate::wasm_fma::#helper(self, #(#args),*) },
            None => {
                quote! { <#base_path as #trait_ident>::#name #turbofish(#extract, #(#args),*) }
            }
        };
        methods.push(quote! {
            #[inline(always)]
            #sig { #body }
        });
    }
    let has_repr = trait_item
        .items
        .iter()
        .any(|item| matches!(item, TraitItem::Type(_)));
    let repr_impl = has_repr.then(|| {
        quote! { type Repr = <#base_path as #trait_ident>::Repr; }
    });
    let cfg_attr = if w512_gated {
        quote! { #[cfg(feature = "w512")] }
    } else {
        quote! {}
    };
    let tokens = quote! {
        #cfg_attr
        impl #trait_ident for #target_tokens {
            #repr_impl
            #(#methods)*
        }
    };
    format!("{tokens}\n\n")
}

//! Higher-tier backend delegation generators (issue #155, #161):
//! - `impls/x86_v3_higher_delegated.rs`: `X64V3CryptoToken`, `X64V3GfniCryptoToken`,
//!   `X64V3VnniToken` → `X64V3Token` (`self.v3()`)
//! - `impls/arm_higher_delegated.rs`: `Arm64V2Token`, `Arm64V3Token` → `NeonToken`
//!   (`self.neon()`)
//! - `impls/wasm128_relaxed_delegated.rs`: `Wasm128RelaxedToken` → `Wasm128Token`
//!   (`self.wasm128()`), overriding `mul_add`, `mul_sub`, `mul_add_portable`, and
//!   `mul_sub_portable` across all float widths to call the per-function
//!   `#[rite]` `relaxed-simd` helpers in `crate::wasm_fma`.
//!
//! Derived from the generated backend trait definitions via `syn`, so a newly
//! added trait method can never silently fall back to its scalar default body.


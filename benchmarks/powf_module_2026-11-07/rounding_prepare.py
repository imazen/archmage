"""Controlled fused/separate study kernels extracted from the owning sources.

No production math changes. Checks and range profiles are explicit consts.
"""
from pathlib import Path
import hashlib
import json
import re
import sys

root = Path(__file__).resolve().parents[2]
out = Path(sys.argv[1])
midp = (root / 'magetypes/src/powf/graph.rs').read_text()
legacy = (root / 'magetypes/src/simd/generic/generated/transcendentals_f32x4.rs').read_text()


def body(name):
    marker = 'pub fn ' + name + '('
    assert legacy.count(marker) == 1
    start = legacy.index('{', legacy.index(marker)) + 1
    depth = 1
    for end in range(start, len(legacy)):
        depth += (legacy[end] == '{') - (legacy[end] == '}')
        if depth == 0:
            return legacy[start:end]
    raise AssertionError('unclosed function ' + name)


def low_body(name, receiver):
    text = body(name).replace('self.1', 'token')
    text = re.sub(r'\bself\b', receiver, text)
    text = text.replace('splat_f32::<T>(token, ', 'sp(')
    text = text.replace('splat_i32::<T>(token, ', 'ip(')
    return text.replace('.mul_add_relaxed(', '.study_madd::<FUSED>(')


prefix = midp[midp.index('            let sp = '):midp.index('            let madd = ')]
prefix = prefix.replace('if GAMMA', 'if DOMAIN == 2').replace('if ZERO', 'if DOMAIN != 0')
prefix = prefix.replace('if invalid.any_true()', 'if CHECKED && invalid.any_true()')
prefix = prefix.replace('ZERO && exponent', 'DOMAIN != 0 && exponent')
arithmetic = midp[midp.index('            let adjusted = '):midp.index('            let result = if ZERO')]
arithmetic = arithmetic.replace('if !GAMMA', 'if CHECKED && DOMAIN != 2')
assert arithmetic.count('let result = p * scale;') == 1
arithmetic = arithmetic.replace('let result = p * scale;', 'p * scale')
assert 'GAMMA' not in prefix and 'ZERO' not in prefix

code = '''// Generated by rounding_prepare.py; benchmark-only controlled kernels.
use magetypes::powf::{PowfError, PowfErrorKind};
trait StudyMadd: Sized {
    fn study_madd<const FUSED: bool>(self, b: Self, c: Self) -> Self;
}
'''
for width in [4, 8, 16]:
    code += f'''
impl<T: magetypes::simd::backends::F32x{width}Convert> StudyMadd
    for magetypes::simd::generic::f32x{width}<T> {{
    #[inline(always)]
    fn study_madd<const FUSED: bool>(self, b: Self, c: Self) -> Self {{
        if FUSED {{ self.mul_add_fused(b, c) }} else {{ self * b + c }}
    }}
}}

#[inline(always)]
pub fn kernel{width}<T: magetypes::simd::backends::F32x{width}Convert,
    const LOWP: bool, const FUSED: bool, const CHECKED: bool, const DOMAIN: usize>(
    token: T, input: magetypes::simd::generic::f32x{width}<T>, exponent: f32,
) -> Result<magetypes::simd::generic::f32x{width}<T>, PowfError> {{
    const {{ assert!(DOMAIN < 3); }}
    use magetypes::simd::generic::{{f32x{width} as V, i32x{width} as I}};
    if CHECKED {{
        let bits = exponent.to_bits() & 0x7fff_ffff;
        if bits >= 0x7f80_0000 || (bits != 0 && bits < 0x0080_0000)
            || (DOMAIN == 2 && !(0.0..=4.0).contains(&exponent)) {{
            return Err(PowfError {{ kind: PowfErrorKind::InvalidExponent,
                lane_mask: ((1_u32 << {width}) - 1) as u16 }});
        }}
    }}
{prefix}
    let result = if LOWP {{
        let log = {{ {low_body('log2_lowp', 'x')} }};
        let t = log * sp(exponent);
        if CHECKED && DOMAIN != 2 {{
            let outside = (t.simd_lt(sp(-126.0)) | t.simd_gt(sp(127.5))).bitcast_to_i32();
            // Admitted zero has an explicit result, independent of LOWP's
            // nonzero log2(1) bias and the size of the positive exponent.
            let outside = if DOMAIN != 0 {{ outside & !zero }} else {{ outside }};
            if outside.any_true() {{
                return Err(reject(outside, PowfErrorKind::OutsideApproximationRange));
            }}
        }}
        {{ {low_body('exp2_lowp', 't')} }}
    }} else {{
        let madd = |a: V<T>, b: V<T>, c: V<T>| a.study_madd::<FUSED>(b, c);
{arithmetic}
    }};
    Ok(if DOMAIN != 0 {{
        V::blend(zero.bitcast_to_f32(), sp(if exponent == 0.0 {{1.0}} else {{0.0}}), result)
    }} else {{result}})
}}
'''
(out / 'rounding_kernels.rs').write_text(code)
(out / 'rounding_kernels.meta.json').write_text(json.dumps({
    'midp_source_sha256': hashlib.sha256(midp.encode()).hexdigest(),
    'lowp_source_sha256': hashlib.sha256(legacy.encode()).hexdigest(),
    'generated_sha256': hashlib.sha256(code.encode()).hexdigest(),
    'fused': 'magetypes mul_add_fused',
    'separate': 'Rust multiply followed by add; assembly and rational oracle checked',
}, indent=2) + '\n')

probes = ''
calls = []
for width in [4,8,16]:
    for lowp in [False,True]:
        for fused in [False,True]:
            name=f'roundprobe_{"lowp" if lowp else "midp"}_{"fused" if fused else "separate"}_x{width}'
            probes+=f'''#[archmage::magetypes(v3,neon,wasm128,scalar)]
#[inline(never)]
pub fn {name}(token:Token,input:&[f32;{width}],n:f32,output:&mut[f32;{width}]) {{
    let v=magetypes::simd::generic::f32x{width}::from_array_t(token,*input);
    *output=archmage_powf_study::rounding::kernel{width}::<Token,{str(lowp).lower()},{str(fused).lower()},true,2>(token,v,n).unwrap().to_array();
}}
'''
            calls.append((name,width))
            # Guaranteed-feature targets can inline the macro wrapper despite
            # the inner attribute. Keep a plain non-inlined caller inspectable.
            for tier,ty,cfg in [('neon','NeonToken','target_arch="aarch64"'),('wasm128','Wasm128Token','target_arch="wasm32"')]:
                probes+=f'''#[cfg({cfg})]
#[inline(never)]
pub fn caller_{name}_{tier}(token:archmage::{ty},input:&[f32;{width}],n:f32,output:&mut[f32;{width}]) {{
    {name}_{tier}(token,input,n,output);
}}
'''
probes+='fn main(){use archmage::SimdToken;let n=std::hint::black_box(2.4_f32);\n'
for width in [4,8,16]:
    probes+=f'let input{width}=std::hint::black_box([0.75;{width}]);let mut output{width}=[0.;{width}];\n'
for tier,ty,cfg in [('scalar','ScalarToken',None),('v3','X64V3Token','target_arch="x86_64"'),('neon','NeonToken','target_arch="aarch64"'),('wasm128','Wasm128Token','target_arch="wasm32"')]:
    if cfg:probes+=f'#[cfg({cfg})]\n'
    probes+=f'if let Some(token)=archmage::{ty}::summon(){{\n'
    for name,width in calls:
        caller=f'caller_{name}_{tier}' if tier in ['neon','wasm128'] else f'{name}_{tier}'
        probes+=f'{caller}(token,&input{width},n,&mut output{width});std::hint::black_box(output{width});\n'
    probes+='}\n'
probes+='}\n'
(out/'rounding_probes.rs').write_text(probes)

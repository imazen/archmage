use std::{env, path::PathBuf, process::Command};

fn main() {
    let directory = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let output = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    assert!(
        Command::new("python3")
            .arg(directory.join("policy_prepare.py"))
            .arg(&output)
            .status()
            .unwrap()
            .success()
    );
    println!("cargo:rerun-if-changed=policy_prepare.py");
    println!("cargo:rerun-if-changed=highp_reference.rs");
    assert!(
        Command::new("python3")
            .arg(directory.join("policy_analyze.py"))
            .arg(&output)
            .status()
            .unwrap()
            .success()
    );
    println!("cargo:rerun-if-changed=policy_analyze.py");
    assert!(
        Command::new("python3")
            .arg(directory.join("rounding_bench_prepare.py"))
            .arg(&output)
            .status()
            .unwrap()
            .success()
    );
    println!("cargo:rerun-if-changed=rounding_bench_prepare.py");
    assert!(
        Command::new("python3")
            .arg(directory.join("prepare.py"))
            .arg(&output)
            .status()
            .unwrap()
            .success()
    );
    assert!(
        Command::new("python3")
            .arg(directory.join("replacement_prepare.py"))
            .arg(&output)
            .status()
            .unwrap()
            .success()
    );
    assert!(
        Command::new("python3")
            .arg(directory.join("codegen_prepare.py"))
            .arg(&output)
            .status()
            .unwrap()
            .success()
    );
    println!("cargo:rerun-if-changed=codegen_prepare.py");
    assert!(
        Command::new("python3")
            .arg(directory.join("rounding_prepare.py"))
            .arg(&output)
            .status()
            .unwrap()
            .success()
    );
    println!("cargo:rerun-if-changed=rounding_prepare.py");
    println!("cargo:rerun-if-changed=reference_graph.rs");
    println!(
        "cargo:rerun-if-changed=../../magetypes/src/simd/generic/generated/transcendentals_f32x4.rs"
    );
    println!("cargo:rerun-if-changed=replacement_prepare.py");
    println!("cargo:rerun-if-changed=prepare.py");
    println!("cargo:rerun-if-changed=../../magetypes/src/powf/graph.rs");
    println!("cargo:rerun-if-changed=../../magetypes/src/soft_fma.rs");
}

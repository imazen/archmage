#!/usr/bin/env python3
"""Exact-v coefficient/error generator; every budget derives from exact fractions."""
import argparse
from fractions import Fraction as F
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess
from mpfr_support import RN,lib,bits32,bits64,f32,f64,certify_fraction,certify_power,rounded_fraction

U=F(1,2**53)
ETA=F(1,2**1075)
H=F(1,2)


def pow2ceil(value):
    e=value.numerator.bit_length()-value.denominator.bit_length()
    if F(2)**e<value:e+=1
    result=F(2)**e
    if result<value:raise ValueError('downward power2 budget')
    return result


def coeffs(p,n):
    result=[F(1)]
    for k in range(1,n+1):result.append(result[-1]*(p-(k-1))/k*F(2,3))
    return result


def polynomial_add(a,b):
    result=[F(0)]*max(len(a),len(b))
    for i,value in enumerate(a):result[i]+=value
    for i,value in enumerate(b):result[i]+=value
    return result


def polynomial_mul(a,b):
    result=[F(0)]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        for j,y in enumerate(b):result[i+j]+=x*y
    return result


def magnitude(polynomial):return sum(abs(v)*H**i for i,v in enumerate(polynomial))

class Node:
    def __init__(self,polynomial,error=F(0),name=''):
        self.poly=polynomial;self.error=error;self.name=name;self.bound=magnitude(polynomial)

class Dag:
    def __init__(self):self.lines=[];self.largest=F(0);self.operations=0
    def op(self,a,b,kind):
        if kind=='+':
            poly=polynomial_add(a.poly,b.poly)
            error=a.error+b.error+U*(a.bound+b.bound+a.error+b.error)+ETA
        else:
            poly=polynomial_mul(a.poly,b.poly)
            error=a.bound*b.error+b.bound*a.error+a.error*b.error+U*(a.bound+a.error)*(b.bound+b.error)+ETA
        name=f'z{self.operations}';self.operations+=1
        node=Node(poly,error,name)
        self.lines.append(f'let {name} = {a.name} {kind} {b.name};')
        self.largest=max(self.largest,node.bound+error)
        if node.bound+error>=8:raise ValueError('DAG intermediate bound >=8')
        return node


def estrin(stored,n):
    dag=Dag();nodes=[Node([x],name=f'COEFF[K][{i}]') for i,x in enumerate(stored[:n+1])]
    power=Node([F(0),F(1)],name='v')
    while len(nodes)>1:
        next_nodes=[]
        for i in range(0,len(nodes),2):
            if i+1<len(nodes):next_nodes.append(dag.op(nodes[i],dag.op(nodes[i+1],power,'*'),'+'))
            else:next_nodes.append(nodes[i])
        nodes=next_nodes
        if len(nodes)>1:power=dag.op(power,power,'*')
    if nodes[0].poly!=stored[:n+1]:raise ValueError('Estrin expression does not equal stored polynomial')
    return nodes[0].error,dag.lines,nodes[0].name,dag.largest,dag.operations


def facts():
    l64=0.003041282560127521;a64=0.0550107189475866;ap64=1.0550107189475866
    s64=rounded_fraction(F(12.92)*F(l64))
    l,s,a,ap=[rounded_fraction(F(x),32) for x in [l64,s64,a64,ap64]]
    decode_min=rounded_fraction(F(rounded_fraction(F(s)+F(a),32))/F(ap),32)
    decode_p=rounded_fraction(F(12,5),32)
    encode_p=rounded_fraction(F(rounded_fraction(1/F(2.4))),32)
    return dict(linear_cutoff_bits=bits32(l),srgb_cutoff_bits=bits32(s),a_bits=bits32(a),ap1_bits=bits32(ap),linear_scale_bits=bits32(rounded_fraction(1/F(12.92),32)),decode_min_bits=bits32(decode_min),encode_min_bits=bits32(l),decode_p_bits=bits32(decode_p),encode_p_bits=bits32(encode_p),linear_cutoff_f64_bits=bits64(l64),srgb_cutoff_f64_bits=bits64(s64),a_f64_bits=bits64(a64),ap1_f64_bits=bits64(ap64))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rust',type=Path,required=True)
    parser.add_argument('--proof',type=Path,required=True)
    parser.add_argument('--summary',type=Path,required=True)
    parser.add_argument('--rustfmt',default=None)
    args=parser.parse_args()
    info=facts();report=dict(version=1,mpfr=lib.mpfr_get_version().decode(),precision=1024,facts=info,cases=[])
    text='// Generated by generate.py; exact binary64 bits, no decimal reparsing.\n'
    for name,number in info.items():
        if name.endswith('_f64_bits'):text+=f'pub(crate) const {name.upper()}:u64=0x{number:016x};\n'
        else:text+=f'pub(crate) const {name.upper()}:u32=0x{number:08x};\n'
    coefficients=[];coef_cert_rows=[];factor_rows=[];error_rows=[];function_code=[];summary=['kind,degree,layout,tail_upper,eval_upper,max_error_power2,max_suffix_upper\n']
    for kind in ['decode','encode']:
        p=F(f32(info[kind+'_p_bits']));a=coeffs(p,21)
        if not 0<p<3:raise ValueError('exponent outside proof')
        cert=[certify_fraction(x) for x in a[:21]]
        stored=[F(c['value']) for c in cert]
        if max(map(abs,stored))>2:raise ValueError('coefficient invariant')
        coefficients.append([c['value'] for c in cert]);coef_cert_rows.append(cert)
        table=[certify_power(math.ldexp(1.5,e),float(p)) for e in range(-9,1)]
        factor_rows.append([t['value'] for t in table]);kind_errors=[]
        for layout in ['horner','estrin']:
            layout_errors=[]
            for n in range(8,21):
                tail=F(3,2)*abs(a[n+1])*H**(n+1)
                cerror=sum(abs(stored[k]-a[k])*H**k for k in range(n+1))
                s=sum(abs(stored[k])*H**k for k in range(n+1))
                suffix=max((1+2*(n-j)*U/(1-2*(n-j)*U))*sum(abs(stored[k])*H**(k-j) for k in range(j,n+1))+8*(n-j)*ETA for j in range(n+1))
                if suffix>=8:raise ValueError('suffix bound')
                if layout=='horner':
                    evaluation=2*n*U/(1-2*n*U)*s+8*n*ETA
                    ops=2*n
                else:
                    evaluation,lines,last,largest,ops=estrin(stored,n)
                    # Code is independent of K; generate once and compile-time index coefficients.
                    if kind=='decode':
                        function_code.append(f'#[inline(always)]\npub(crate) fn estrin_{n}<const K:usize>(v:f64)->f64 {{\n'+''.join('    '+line+'\n' for line in lines[:-1])+f'    {lines[-1].split(" = ",1)[1][:-1]}\n}}\n')
                epoly=tail+cerror+evaluation
                b=sum(abs(a[k])*H**k for k in range(n+1))+tail
                if epoly>=F(1,64):raise ValueError('polynomial lower margin')
                errors=[];details=[]
                for e,t in zip(range(-9,1),table):
                    stored_t=F(t['value']);dt=max(abs(stored_t-F(t['lower'])),abs(F(t['upper'])-stored_t))
                    if not F(1,2**32)<F(t['lower']) or stored_t>=4 or dt>=stored_t/F(2**48):raise ValueError('table margins')
                    total=stored_t*epoly+dt*b+U*stored_t*(s+evaluation)+ETA
                    pad=pow2ceil(total)
                    lower=stored_t*(F(1,4)-epoly)-U*stored_t*(s+evaluation)-ETA
                    upper=stored_t*(s+evaluation)*(1+U)+ETA
                    if not lower>stored_t/8 or not pad<stored_t/32 or not upper+pad<64:raise ValueError('positive finite endpoint invariant')
                    errors.append(float(pad));details.append(dict(exponent=e,table_bits=f'{bits64(t["value"]):016x}',table_lower_bits=f'{bits64(t["lower"]):016x}',table_upper_bits=f'{bits64(t["upper"]):016x}',delta_bits=f'{bits64(float(pad)):016x}'))
                layout_errors.append(errors)
                tail_up,eval_up,suffix_up=[math.nextafter(float(z),math.inf) for z in [tail,evaluation,suffix]]
                report['cases'].append(dict(kind=kind,degree=n,layout=layout,operations=ops,tail_upper=tail_up,coefficient_error_upper=math.nextafter(float(cerror),math.inf),evaluation_error_upper=eval_up,suffix_upper=suffix_up,table=details))
                summary.append(f'{kind},{n},{layout},{tail_up:.18e},{eval_up:.18e},{max(errors).hex()},{suffix_up:.18e}\n')
            kind_errors.append(layout_errors)
        error_rows.append(kind_errors)
    def literal(value):return f'f64::from_bits(0x{bits64(value):016x})'
    text+='pub(crate) const COEFF:[[f64;21];2]=[\n'+''.join('    ['+','.join(map(literal,row))+'],\n' for row in coefficients)+'];\n'
    text+='pub(crate) const FACTOR:[[f64;10];2]=[\n'+''.join('    ['+','.join(map(literal,row))+'],\n' for row in factor_rows)+'];\n'
    text+='pub(crate) const ERROR:[[[[f64;10];13];2];2]=[\n'
    for kind in error_rows:
        text+='    [\n'
        for layout in kind:text+='        [\n'+''.join('            ['+','.join(map(literal,row))+'],\n' for row in layout)+'        ],\n'
        text+='    ],\n'
    text+='];\n'+''.join(function_code)
    text+='#[inline(always)]\npub(crate) fn estrin<const K:usize,const N:usize>(v:f64)->f64 {\n    match N {\n'+''.join(f'        {n} => estrin_{n}::<K>(v),\n' for n in range(8,21))+'        _ => panic!("unsupported degree"),\n    }\n}\n'
    report['coefficients']=[[dict(bits=f'{bits64(c):016x}',lower_bits=f'{bits64(cert["lower"]):016x}',upper_bits=f'{bits64(cert["upper"]):016x}',exact_numerator=str(a.numerator),exact_denominator=str(a.denominator)) for c,a,cert in zip(row,coeffs(F(f32(info[k+'_p_bits'])),20),certrow)] for k,row,certrow in zip(['decode','encode'],coefficients,coef_cert_rows)]
    args.rust.parent.mkdir(parents=True,exist_ok=True);args.rust.write_text(text)
    if args.rustfmt:
        subprocess.run([args.rustfmt,'--edition','2024',str(args.rust)],check=True)
    report['rust_sha256']=hashlib.sha256(args.rust.read_bytes()).hexdigest()
    args.proof.parent.mkdir(parents=True,exist_ok=True);args.proof.write_text(json.dumps(report,indent=2)+'\n')
    args.summary.write_text(''.join(summary))
    print(json.dumps(dict(mpfr=report['mpfr'],facts=info,rust_sha256=report['rust_sha256'],cases=len(report['cases'])),indent=2))

if __name__=='__main__':main()

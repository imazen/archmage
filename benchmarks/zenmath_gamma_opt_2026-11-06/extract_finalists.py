#!/usr/bin/env python3
"""Extract selected bit literals from frozen proofs; verify every bit against archived compiled Rust."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import tarfile


def sha(data):return hashlib.sha256(data).hexdigest()
def array(value):
    if isinstance(value,list):return '['+','.join(array(v) for v in value)+']'
    return 'f64::from_bits(0x'+value+')'

def main():
    p=argparse.ArgumentParser();p.add_argument('--run',type=Path,required=True);p.add_argument('--out',type=Path,required=True);p.add_argument('--manifest',type=Path,required=True);a=p.parse_args()
    root=a.run;identity=root/'identity';build=json.loads((identity/'build.json').read_text())
    archive=identity/'source.tar.gz'
    if sha(archive.read_bytes())!=build['source_archive_sha256']:raise ValueError('source archive identity')
    global_proof=json.loads((root/'bound-proof.json').read_text());piece_proof=json.loads((root/'piece-bound-proof.json').read_text())
    with tarfile.open(archive,'r:gz') as tar:
        global_rust=tar.extractfile('source/benchmarks/zenmath_gamma_opt_2026-11-06/src/generated.rs').read()
        piece_rust=tar.extractfile('source/benchmarks/zenmath_gamma_opt_2026-11-06/src/piecewise_generated.rs').read()
    if sha(global_rust)!=global_proof['rust_sha256'] or sha(piece_rust)!=piece_proof['rust_sha256']:raise ValueError('proof/generated source mismatch')
    gb=re.findall(rb'f64::from_bits\(0x([0-9a-f]{16})\)',global_rust);pb=re.findall(rb'f64::from_bits\(0x([0-9a-f]{16})\)',piece_rust)
    gb=[v.decode()for v in gb];pb=[v.decode()for v in pb]
    if len(gb)!=582 or len(pb)!=2432:raise ValueError('original constant inventory')
    def checked(bits,actual):
        if bits!=actual:raise ValueError('selected bit mismatch')
        return bits
    gcoeff=[];gfactor=[];gerror=[];pcoeff=[];pfactor=[];perror=[]
    for k,name in enumerate(['decode','encode']):
        degree=13 if k==0 else 15
        gcoeff.append([checked(v['bits'],gb[k*21+i])for i,v in enumerate(global_proof['coefficients'][k][:degree+1])])
        case=next(c for c in global_proof['cases'] if c['kind']==name and c['degree']==degree and c['layout']=='estrin')
        gfactor.append([checked(v['table_bits'],gb[42+k*10+e])for e,v in enumerate(case['table'])])
        gerror.append([checked(v['delta_bits'],gb[62+k*260+130+(degree-8)*10+e])for e,v in enumerate(case['table'])])
        pc=[];factors=[[None]*16 for _ in range(10)];errors=[[None]*16 for _ in range(10)]
        for j in range(16):
            coeff=next(c for c in piece_proof['coefficients']if c['kind']==name and c['center']==j)
            pc.append([checked(v['bits'],pb[k*96+j*6+i])for i,v in enumerate(coeff['values'])])
            case=next(c for c in piece_proof['cases']if c['kind']==name and c['center']==j and c['degree']==5 and c['layout']=='estrin')
            for e,v in enumerate(case['table']):
                factors[e][j]=checked(v['table_bits'],pb[192+k*160+e*16+j]);errors[e][j]=checked(v['delta_bits'],pb[512+k*960+480+320+e*16+j])
        pcoeff.append(pc);pfactor.append(factors);perror.append(errors)
    arrays=[('GLOBAL_DECODE_COEFF','[f64;14]',gcoeff[0]),('GLOBAL_ENCODE_COEFF','[f64;16]',gcoeff[1]),('GLOBAL_FACTOR','[[f64;10];2]',gfactor),('GLOBAL_ERROR','[[f64;10];2]',gerror),('PIECE_COEFF','[[[f64;6];16];2]',pcoeff),('PIECE_FACTOR','[[[f64;16];10];2]',pfactor),('PIECE_ERROR','[[[f64;16];10];2]',perror)]
    text='// Selected frozen finalist bit literals; generated by extract_finalists.py.\n'
    for name,typ,value in arrays:text+=f'pub(crate) const {name}:{typ}='+array(value)+';\n'
    with a.out.open('x')as out:out.write(text)
    result=dict(source_manifest_sha256=build['source_manifest_sha256'],binary_sha256=build['binary_sha256'],source_archive_sha256=build['source_archive_sha256'],global_proof_sha256=sha((root/'bound-proof.json').read_bytes()),piece_proof_sha256=sha((root/'piece-bound-proof.json').read_bytes()),output_sha256=sha(a.out.read_bytes()),constants=902,global_bytes=560,piece_bytes=6656,total_bytes=7216,checked='every selected bit equals frozen proof AND archived compiled generated Rust')
    with a.manifest.open('x')as out:out.write(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()

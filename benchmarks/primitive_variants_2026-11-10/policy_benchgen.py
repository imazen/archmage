def registry(rows):
    out = ["// Generated by policy_benchgen.py from actual Rust builder output."]
    for family, name, zero in [("minmax","minmax_cases",False),("minmax","zero_cases",True),("recip","recip_cases",False)]:
        flags=sorted({r["bits"] for r in rows if r["family"]==family and r["supported"] and (not zero or r["domain"]!="Normal")})
        assert len(flags)==(20 if zero else 24 if family=="minmax" else 22)
        prefix="M" if family=="minmax" else "R"
        out += [f"macro_rules! {name} {{", "    ($apply:ident) => {{"]
        out += [f'        $apply!({flag}, "{prefix}{flag:02x}");' for flag in flags]
        out += ["    }};", "}"]
    return "\n".join(out)+"\n"



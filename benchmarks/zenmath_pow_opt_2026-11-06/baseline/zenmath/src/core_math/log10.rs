fn two(a: f64, b: f64) -> (f64, f64) {
    let h = a + b;
    (h, b - (h - a))
}
/// Base-ten logarithm, rounded to nearest with ties to even.
pub fn log10(x: f64) -> f64 {
    if x == 0.0 {
        return f64::NEG_INFINITY;
    }
    if x.is_nan() {
        return x + x;
    }
    if x < 0.0 {
        return f64::NAN;
    }
    if x == f64::INFINITY {
        return x;
    }
    let mut v = x;
    let mut bits = v.to_bits();
    let mut e = (bits >> 52) as i32 - 1023;
    if e == -1023 {
        v *= f64::from_bits(0x4330000000000000);
        bits = v.to_bits();
        e = (bits >> 52) as i32 - 1023 - 52;
    }
    const POWERS: [f64; 23] = [
        1.0, 1e1, 1e2, 1e3, 1e4, 1e5, 1e6, 1e7, 1e8, 1e9, 1e10, 1e11, 1e12, 1e13, 1e14, 1e15, 1e16,
        1e17, 1e18, 1e19, 1e20, 1e21, 1e22,
    ];
    if let Some(n) = POWERS.iter().position(|p| p.to_bits() == bits) {
        return n as f64;
    }
    bits = (0x3ff << 52) | (bits & 0xfffffffffffff);
    v = f64::from_bits(bits);
    let m = (1 << 52) | (bits & 0xfffffffffffff);
    let c = usize::from(m >= 0x16a09e667f3bcd);
    e += c as i32;
    let i = (m >> [43, 44][c]) as usize - 362;
    let y = v * [1.0, 0.5][c];
    let r = _INVERSE[i];
    let l1 = _LOG_INV[i][0];
    let l2 = _LOG_INV[i][1];
    let z = fma(r, y, -1.0);
    let z2 = z * z;
    let p45 = fma(P[5], z, P[4]);
    let p23 = fma(P[3], z, P[2]);
    let ph = fma(p45, z2, p23);
    let ph = fma(ph, z, P[1]) * z2;
    let ee = e as f64;
    let (h, l) = two(fma(ee, f64::from_bits(0x3fe62e42fefa3800), l1), z);
    let l = ph + (l + l2);
    let l = fma(ee, f64::from_bits(0x3d2ef35793c76730), l);
    let bh = f64::from_bits(0x3fdbcb7b1526e50e);
    let bl = f64::from_bits(0x3c695355baaafad3);
    let hi = h * bh;
    let s = fma(h, bh, -hi);
    let t = fma(l, bh, s);
    let lo = fma(h, bl, t);
    let err = f64::from_bits(0x3ba0400000000000);
    let left = hi + (lo - err);
    let right = hi + (lo + err);
    if left == right {
        left
    } else {
        super::log_accurate::accurate10(x)
    }
}

#!/usr/bin/env python3
"""Extract the canonical unscaled Arm constants through C, preserving every bit."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('build',type=Path);p.add_argument('output',type=Path)
a=p.parse_args();build=json.loads((a.build/'manifest.json').read_text());source=(a.build/'source').resolve()
assert build['source_revision']=='4be260a5117480382690c6d8c300bc784e927d76'
for name,expected in build['source_files'].items():assert hashlib.sha256((source/name).read_bytes()).hexdigest()==expected
probe=a.build/'data-probe.c'
probe.write_text('''#include "math_config.h"
#include <stdio.h>
#include <inttypes.h>
int main(void) {
 for(int i=0;i<16;i++)printf("L %016" PRIx64 " %016" PRIx64 "\\n",asuint64(__powf_log2_data.tab[i].invc),asuint64(__powf_log2_data.tab[i].logc));
 for(int i=0;i<5;i++)printf("A %016" PRIx64 "\\n",asuint64(__powf_log2_data.poly[i]));
 for(int i=0;i<32;i++)printf("T %016" PRIx64 "\\n",__exp2f_data.tab[i]);
 for(int i=0;i<3;i++)printf("C %016" PRIx64 "\\n",asuint64(__exp2f_data.poly[i]));
 printf("S %016" PRIx64 "\\n",asuint64(__exp2f_data.shift_scaled));
 printf("O %016" PRIx64 "\\n",asuint64(0x1.fffffffd1d571p+6));
 printf("B %016" PRIx64 "\\n",asuint64(0x1.fffffffa3aae2p+6));
}
''')
binary=a.build/'data-probe'
subprocess.run(['cc','-O2','-std=c11','-DHAVE_FAST_ROUND=0','-DHAVE_FAST_LROUND=0','-I',str(source),str(probe),str(source/'powf_log2_data.c'),str(source/'exp2f_data.c'),'-o',str(binary)],check=True)
raw=subprocess.check_output([str(binary)],text=True);(a.build/'data-bits.txt').write_text(raw)
rows={k:[]for k in 'LATCSOB'}
for line in raw.splitlines():
    key,*values=line.split();rows[key].append(values)
assert [len(rows[k])for k in 'LATCSOB']==[16,5,32,3,1,1,1]
text='// Generated by arm_data.py from Arm Optimized Routines v26.07 / 4be260a5.\n// Copyright (c) 2017-2019, Arm Limited. SPDX-License-Identifier: MIT\n// See ARM-LICENSE.txt. Canonical TOINT_INTRINSICS=0 constants.\n'
text+='pub(super) const LOG: [(f64,f64);16] = [\n'+''.join(f'    (f64::from_bits(0x{x}), f64::from_bits(0x{y})),\n'for x,y in rows['L'])+'];\n'
for name,key,size,kind in [('A','A',5,'f64'),('TABLE','T',32,'u64'),('C','C',3,'f64')]:
    text+=f'pub(super) const {name}: [{kind};{size}] = [\n'+''.join('    '+(f'f64::from_bits(0x{v[0]})'if kind=='f64'else f'0x{v[0]}')+',\n'for v in rows[key])+'];\n'
for name,key in [('SHIFT','S'),('OVERFLOW','O'),('OVERFLOW_BOUND','B')]:text+=f'pub(super) const {name}: f64 = f64::from_bits(0x{rows[key][0][0]});\n'
a.output.write_text(text)
subprocess.run(['rustfmt','--edition','2024',str(a.output)],check=True)
print(json.dumps({'source_revision':build['source_revision'],'output_sha256':hashlib.sha256(a.output.read_bytes()).hexdigest(),'constants':len(raw.splitlines())}))

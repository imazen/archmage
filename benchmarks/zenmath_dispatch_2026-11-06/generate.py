#!/usr/bin/env python3
"""Reproducible complete loops, proof-bearing selectors and dispatch controls."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent
TIERS = [
    ("scalar", "ScalarToken", None),
    ("v2", "X64V2Token", 'target_arch="x86_64"'),
    ("v3", "X64V3Token", 'target_arch="x86_64"'),
    ("v4x", "X64V4xToken", 'all(target_arch="x86_64",feature="avx512")'),
    ("neon", "NeonToken", 'target_arch="aarch64"'),
    ("wasm128", "Wasm128Token", 'target_arch="wasm32"'),
]
SELECTORS = ",".join(
    f"_{tier},_{tier}_t" if tier != "v4x" else "_v4x(cfg(avx512)),_v4x_t(cfg(avx512))"
    for tier, _, _ in TIERS
)
OPS = [
    ("sqrt", "sqrtf", "x.sqrt()"),
    ("floor", "floorf", "x.floor()"),
    ("ceil", "ceilf", "x.ceil()"),
    ("trunc", "truncf", "x.trunc()"),
    ("roundeven", "roundevenf", "x.round_ties_even()"),
    ("round", "roundf", "x.round()"),
    ("fma", "fmaf", "x.mul_add(y,z)"),
    ("exp", "expf", "x.exp()"),
    ("ln", "logf", "x.ln()"),
    ("log2", "log2f", "x.log2()"),
    ("pow", "powf", "x.powf(y)"),
    ("pow_rescue", "powf", "x.powf(y)"),
]
source = [
    "//! Generated by generate.py; no unsafe, no CPU-native flags.\nuse archmage::prelude::*;\nuse std::sync::OnceLock;\nuse crate::{Case,Kernel};\n"
]
source += [
    """#[derive(Clone,Copy)]
enum Proof {
 Scalar,
 #[cfg(target_arch="x86_64")] V1(X64V1Token),
 #[cfg(target_arch="x86_64")] V2(X64V2Token),
 #[cfg(target_arch="x86_64")] V3(X64V3Token),
 #[cfg(target_arch="aarch64")] Neon(NeonToken),
 #[cfg(target_arch="wasm32")] Wasm(Wasm128Token),
}
"""
]
for ty, suf, ops in [("f32", "32", OPS), ("f64", "64", OPS[:7])]:
    case_rows = []
    for op, original, stdexpr in ops:
        api = original if ty == "f32" else original.removesuffix("f")
        base = op + "_" + ty
        binary = api.startswith("pow")
        ternary = api.startswith("fma")
        actual_args = "x,y,z" if ternary else "x,y" if binary else "x"
        ref = (
            f"zenmath::scalar::reference::floor{'f' if ty == 'f32' else ''}(x.abs()).copysign(x)"
            if op == "trunc"
            else f"zenmath::scalar::reference::{api}({actual_args})"
        )
        choices = []
        for tier, token, guard in TIERS:
            if tier in ["scalar", "v4x"]:
                continue
            if tier == "v2":
                if api.startswith("sqrt"):
                    choices.append(("v1", "X64V1Token", guard, "V1"))
                elif op in ["floor", "ceil", "trunc", "roundeven", "round"]:
                    choices.append((tier, token, guard, "V2"))
                continue
            if tier == "v3" and op in [
                "sqrt",
                "floor",
                "ceil",
                "trunc",
                "roundeven",
                "round",
            ]:
                continue
            choices.append(
                (tier, token, guard, "Wasm" if tier == "wasm128" else tier.title())
            )
        selected = "Selected" + "".join(part.capitalize() for part in base.split("_"))
        calltype = "Call" + "".join(part.capitalize() for part in base.split("_"))
        pointer_args = (
            f"x:{ty}"
            + (f",y:{ty}" if binary or ternary else "")
            + (f",z:{ty}" if ternary else "")
        )
        pointer_types = (
            ty + ("," + ty if binary or ternary else "") + ("," + ty if ternary else "")
        )
        source += [
            f"type {calltype}=fn(Proof,{pointer_types})->{ty};\n#[derive(Clone,Copy)]struct {selected}{{call:{calltype},proof:Proof}}\n"
        ]
        # Safe function pointer carries a real proof in its context. It is not an IFUNC.
        source += [f"fn {base}_ptr_scalar(_:Proof,{pointer_args})->{ty}{{{ref}}}\n"]
        for tier, token, guard, variant in choices:
            source += [
                f'#[cfg({guard})]\nfn {base}_ptr_{tier}(p:Proof,{pointer_args})->{ty}{{let Proof::{variant}(t)=p else{{unreachable!("selector/proof mismatch")}};zenmath::simd::scalar::{api}_{tier}_t(t,{actual_args})}}\n'
            ]
        source += [f"fn {base}_select()->{selected}{{\n"]
        for tier, token, guard, variant in choices:
            source += [
                f"#[cfg({guard})]\nif let Some(t)={token}::summon(){{return {selected}{{call:{base}_ptr_{tier},proof:Proof::{variant}(t)}};}}\n"
            ]
        source += [f"{selected}{{call:{base}_ptr_scalar,proof:Proof::Scalar}}\n}}\n"]
        source += [
            f"#[inline]\nfn {base}_cached(x:{ty},y:{ty},z:{ty})->{ty}{{let _=(y,z);static C:OnceLock<{selected}>=OnceLock::new();let c=C.get_or_init({base}_select);(c.call)(c.proof,{actual_args})}}\n"
        ]
        source += [
            f"#[inline]\nfn {base}_branch(x:{ty},y:{ty},z:{ty})->{ty}{{let _=(y,z);\n"
        ]
        for tier, token, guard, _ in choices:
            source += [
                f"#[cfg({guard})]\nif let Some(t)={token}::summon(){{return zenmath::simd::scalar::{api}_{tier}_t(t,{actual_args});}}\n"
            ]
        source += [f"{ref}\n}}\n"]

        def body(expression, feedback):
            pre = "assert_eq!(input.len(),out.len());assert_eq!(input.len(),ys.len());assert_eq!(input.len(),zs.len());\n"
            if not feedback:
                return (
                    pre
                    + f"for i in 0..input.len(){{let (x,y,z)=(input[i],ys[i],zs[i]);let _=(y,z);out[i]={expression};}}\n"
                )
            mapping = {
                "sqrt": "let x=value.abs()+0.125;",
                "floor": "let x=value*0.125+0.375;",
                "round": "let x=value*0.125+0.375;",
                "ceil": "let x=value*0.125+0.375;",
                "trunc": "let x=value*0.125+0.375;",
                "roundeven": "let x=value*0.125+0.375;",
                "fma": f"let (x,y,z)=(value,0.999_{ty},0.0001_{ty});",
                "exp": "let x=-value.abs()*0.125;",
                "ln": "let x=value.abs()+1.1;",
                "log2": "let x=value.abs()+1.1;",
                "pow": "let (x,y)=(value.abs()*0.125+0.75,2.4);",
                "pow_rescue": "let (x,y)=(value.abs()*0.125+0.75,2.4);",
            }[op]
            return (
                pre
                + f"assert!(!input.is_empty());let mut value=input[0];let(y,z)=(ys[0],zs[0]);let _=(y,z);for _ in 0..1024{{{mapping}value={expression};}}out[0]=value;\n"
            )

        for feedback in [False, True]:
            if feedback and op == "pow_rescue":
                continue
            kind = "feedback" if feedback else "stream"
            sig = f"input:&[{ty}],ys:&[{ty}],zs:&[{ty}],out:&mut[{ty}]"
            prefix = base + "_" + kind
            for form, expression in [
                ("reference", ref),
                ("std", stdexpr),
                ("branch", f"{base}_branch(x,y,z)"),
                ("cached", f"{base}_cached(x,y,z)"),
                ("ordinary", ref if op == "trunc" else f"zenmath::scalar::{api}({actual_args})"),
            ]:
                source += [
                    f"#[inline(never)]\npub fn {prefix}_{form}({sig}){{\n{body(expression, feedback)}}}\n"
                ]
            # std loop contexts are controls for autovectorization/context alone.
            source += [
                f"#[archmage::attune({SELECTORS},inline(never))]\npub fn {prefix}_stdctx({sig}){{{body(stdexpr, feedback)}}}\n"
            ]
            # Write concrete bodies: no implicit attuned! probes inside a loop.
            for tier, _, _ in TIERS:
                if tier == "scalar":
                    expression = ref
                else:
                    primitive = (
                        "v1"
                        if op == "sqrt" and tier.startswith("v")
                        else "v2"
                        if op in ["floor", "ceil", "trunc", "roundeven", "round"]
                        and tier.startswith("v")
                        else "scalar"
                        if tier == "v2"
                        else "v3"
                        if tier == "v4x" and ternary
                        else tier
                    )
                    expression = (
                        f"zenmath::simd::scalar::{api}_{primitive}({actual_args})"
                    )
                selector = (
                    f"_{tier},_{tier}_t"
                    if tier != "v4x"
                    else "_v4x(cfg(avx512)),_v4x_t(cfg(avx512))"
                )
                source += [
                    f"#[archmage::attune({selector},inline(never))]\npub fn {prefix}_context({sig}){{{body(expression, feedback)}}}\n"
                ]
            source += [
                f"pub fn {prefix}_cases()->Vec<Case<{ty}>>{{let mut v:Vec<Case<{ty}>>=vec![\n"
            ]
            for form in ["reference", "std", "branch", "cached", "ordinary"]:
                source += [
                    f'Case{{name:"{form}/baseline",run:Box::new({prefix}_{form}) as Kernel<{ty}>}},\n'
                ]
            source += ["];\n"]
            for tier, token, guard in TIERS:
                if tier == "scalar":
                    continue
                source += [f"#[cfg({guard})]\nif let Some(t)={token}::summon(){{\n"]
                source += [
                    f'v.push(Case{{name:"context/{tier}",run:Box::new(move|x,y,z,o|{prefix}_context_{tier}_t(t,x,y,z,o))}});\n'
                ]
                source += [
                    f'v.push(Case{{name:"std-context/{tier}",run:Box::new(move|x,y,z,o|{prefix}_stdctx_{tier}_t(t,x,y,z,o))}});\n'
                ]
                source += ["}\n"]
            for tier, token, guard, _ in choices:
                source += [
                    f'#[cfg({guard})]\nif let Some(t)={token}::summon(){{v.push(Case{{name:"proof/{tier}",run:Box::new(move|input,ys,zs,out|{{{body(f"zenmath::simd::scalar::{api}_{tier}_t(t,{actual_args})", feedback)}}})}});}}\n'
                ]
            if (
                not feedback
                and ty == "f32"
                and op in ["exp", "ln", "log2", "pow", "pow_rescue"]
            ):
                vector_op = "pow" if op == "pow_rescue" else op
                for tier, token, guard in TIERS:
                    if tier in ["scalar", "v2"]:
                        continue
                    source += [
                        f'#[cfg({guard})]\nif let Some(t)={token}::summon(){{v.push(Case{{name:"packed4/{tier}",run:Box::new(move|input,ys,_zs,out|{{assert_eq!(input.len(),out.len());assert_eq!(input.len(),ys.len());out.copy_from_slice(input);zenmath::simd::slice::{vector_op}_f32_{tier}_t(t,out'
                        + (",ys" if vector_op == "pow" else "")
                        + ");})});}\n"
                    ]
                source += [
                    f'#[cfg(all(target_arch="x86_64",feature="avx512"))]\nif let Some(t)=X64V4xToken::summon(){{v.push(Case{{name:"packed8/v4x",run:Box::new(move|input,ys,_zs,out|{{assert_eq!(input.len(),out.len());assert_eq!(input.len(),ys.len());out.copy_from_slice(input);zenmath::simd::slice::{vector_op}_f32_wide_v4x_t(t,out'
                    + (",ys" if vector_op == "pow" else "")
                    + ");})});}\n"
                ]
            source += ["v\n}\n"]
        case_rows.append((op, base))
    source += [
        f"pub fn cases{suf}(op:&str,feedback:bool)->Vec<Case<{ty}>>{{match(op,feedback){{\n"
    ]
    for op, base in case_rows:
        source += [f'("{op}",false)=>{base}_stream_cases(),\n']
        if op != "pow_rescue":
            source += [f'("{op}",true)=>{base}_feedback_cases(),\n']
    source += ['_=>panic!("unsupported workload"),}}\n']
(ROOT / "src/generated.rs").write_text("".join(source))
